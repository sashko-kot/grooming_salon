// Пакет "service" — здесь располагают СЕРВИСНЫЙ СЛОЙ приложения: код,
// который содержит бизнес-логику и правила проверки данных, но НЕ занимается
// напрямую ни хранением данных (это работа repository), ни отображением
// интерфейса пользователю (это работа контроллеров/UI). Сервисный слой —
// "прослойка" между ними, координирующая их работу.
package ru.mirea.service;

// Импортируем модель услуги — сервис работает с объектами GroomingService,
// проверяет их корректность и передаёт репозиторию для сохранения.
import ru.mirea.model.GroomingService;

// Импортируем КОНКРЕТНУЮ реализацию репозитория (GroomingServiceJdbcRepository),
// а НЕ интерфейс GroomingServiceRepository. Это важный момент для обсуждения —
// см. подробный комментарий у поля repository ниже: с точки зрения хорошей
// архитектуры (принцип "программируй на уровне интерфейса, а не реализации",
// который обсуждался в комментариях к самому интерфейсу репозитория) было бы
// предпочтительнее, чтобы сервис зависел от абстракции GroomingServiceRepository,
// а не от конкретного класса с "привязкой" к JDBC.
import ru.mirea.repository.GroomingServiceJdbcRepository;

// BigDecimal — тип для точных денежных вычислений, используется здесь
// для параметров цены и для сравнения с нулём при валидации.
import java.math.BigDecimal;

// List — интерфейс списка, тип возвращаемого значения метода getAllServices().
import java.util.List;

// Optional — "обёртка" для значения, которое может отсутствовать; используется
// в методе getServiceById(), который просто "прокидывает" результат репозитория
// дальше без изменений.
import java.util.Optional;

// Комментарий-описание класса.
// Бизнес-логика приложения.
// Этот класс проверяет данные и вызывает репозиторий для работы с услугами.

// "public" — сервис вызывается извне пакета service: например, из контроллеров
// (веб или консольного интерфейса), которым нужно добавить/найти/обновить услугу,
// не разбираясь в деталях проверки данных и работы с базой самостоятельно.
//
// "class" (обычный, изменяемый по своей природе объект, а не record и не
// интерфейс) — выбран, потому что GroomingServiceService — это объект
// СО СВОИМ ПОВЕДЕНИЕМ (методы с логикой валидации и координации), а не просто
// контейнер данных (в отличие от record'ов GroomingService/Appointment)
// и не абстрактный контракт (в отличие от интерфейса GroomingServiceRepository).
// У сервиса есть состояние — поле repository (см. ниже), которое устанавливается
// один раз при создании объекта и используется во всех методах.
public class GroomingServiceService {

    // "private" — поле видно ТОЛЬКО внутри этого класса, снаружи никто не должен
    // напрямую подменять или читать репозиторий сервиса — это внутренняя деталь
    // реализации, доступ к репозиторию для внешнего кода должен идти ИСКЛЮЧИТЕЛЬНО
    // через публичные методы сервиса (getAllServices, addService и т.д.),
    // а не напрямую в обход бизнес-логики и проверок сервиса.
    //
    // "final" — поле присваивается ОДИН РАЗ, в конструкторе, и больше никогда
    // не переприсваивается за время жизни объекта GroomingServiceService.
    // Это распространённый и правильный подход для зависимостей объекта:
    // раз репозиторий передан при создании сервиса, он не должен "подменяться"
    // потом на другой в середине работы — если нужен другой репозиторий,
    // логичнее создать новый объект сервиса с этим другим репозиторием.
    //
    // Тип поля "GroomingServiceJdbcRepository" (конкретный класс), а НЕ интерфейс
    // "GroomingServiceRepository" — это архитектурно спорное решение (важно уметь
    // объяснить обе стороны, если спросят на защите):
    // Минус такого подхода: сервис оказывается ЖЁСТКО привязан именно к
    // JDBC-реализации.
    // Если бы понадобилось протестировать GroomingServiceService в юнит-тестах
    // с "поддельным" репозиторием (например, простым списком в памяти вместо
    // реальной базы данных) или в будущем перейти на другую технологию хранения
    // (JPA/Hibernate), пришлось бы либо переписывать этот класс, либо создавать
    // "поддельный" объект именно типа GroomingServiceJdbcRepository (что неудобно,
    // так как это конкретный класс, а не интерфейс, который проще подменить).
    // Правильнее с точки зрения принципа "программируй на уровне интерфейса"
    // было бы объявить поле как "private final GroomingServiceRepository
    // repository;"
    // — тогда сервис работал бы с ЛЮБОЙ реализацией контракта репозитория,
    // не зная и не заботясь о технических деталях конкретной реализации.
    private final GroomingServiceJdbcRepository repository;

    // Комментарий-описание конструктора.
    // В конструктор передаётся репозиторий для работы с БД.

    // "public" — конструктор должен вызываться извне класса, чтобы можно было
    // создать объект сервиса (например, в точке входа приложения: main-методе
    // или в конфигурации Spring, если бы проект использовал Spring Framework).
    // Параметр "GroomingServiceJdbcRepository repository" передаётся СНАРУЖИ,
    // а не создаётся сервисом самостоятельно (например, через
    // "new GroomingServiceJdbcRepository()" прямо внутри конструктора) —
    // это называется "внедрение зависимости через конструктор" (constructor
    // dependency injection). Такой подход даёт гибкость: КТО-ТО СНАРУЖИ решает,
    // какой конкретно репозиторий передать сервису, а сам сервис ничего
    // не знает о том, КАК этот репозиторий был создан и настроен (какие
    // логин/пароль/URL использовались для подключения к базе и т.д.).
    public GroomingServiceService(GroomingServiceJdbcRepository repository) {
        // "this.repository" — обращение к ПОЛЮ класса, чтобы отличить его
        // от ПАРАМЕТРА конструктора с точно таким же именем "repository".
        // Без "this." строка "repository = repository;" присвоила бы параметр
        // самому себе и никак не сохранила бы значение в поле объекта —
        // "this" здесь обязателен именно из-за совпадения имён параметра и поля
        // (это стандартный и очень распространённый стиль именования в Java).
        this.repository = repository;
    }

    // Комментарий-описание метода.
    // Возвращает список всех услуг.

    // Простой метод-"обёртка" (wrapper): он не добавляет никакой собственной
    // логики поверх репозитория, а просто ПЕРЕДАЁТ вызов дальше в
    // repository.findAll()
    // и возвращает результат как есть. Смысл существования такого метода —
    // сохранить единую точку входа через сервисный слой: контроллеры/UI-код
    // всегда обращаются именно к сервису, а не напрямую к репозиторию, даже
    // если в конкретном случае сервис пока не добавляет ничего "своего" —
    // это упрощает добавление логики в будущем (например, кэширования
    // или сортировки) в ОДНОМ месте, не меняя код всех вызывающих сторон.
    public List<GroomingService> getAllServices() {
        return repository.findAll();
    }

    // Комментарий-описание метода.
    // Добавляет готовый объект услуги после проверки корректности.

    // Это ПЕРВАЯ из ДВУХ версий метода addService в этом классе — они называются
    // ОДИНАКОВО ("addService"), но принимают РАЗНЫЕ наборы параметров
    // (один параметр GroomingService против четырёх отдельных параметров ниже).
    // Это называется ПЕРЕГРУЗКОЙ МЕТОДОВ (method overloading) — возможность
    // иметь в одном классе несколько методов с одинаковым именем, если у них
    // разная "сигнатура" (набор и/или типы параметров). Компилятор сам определяет,
    // КАКОЙ именно вариант метода вызвать, глядя на то, что именно передал
    // вызывающий код (готовый объект GroomingService или отдельные поля).
    //
    // "void" — метод ничего не возвращает: либо услуга успешно добавлена,
    // либо метод выбросит исключение при некорректных данных (см. validateService).
    public void addService(GroomingService service) {
        // Сначала проверяем корректность переданного объекта через отдельный
        // приватный метод validateService (объявлен в самом низу класса) —
        // если что-то не так, validateService сам бросит исключение,
        // и строка repository.save(service) ниже просто не выполнится.
        validateService(service);
        // Если проверка прошла успешно (исключение не было выброшено),
        // передаём объект репозиторию для реального сохранения в хранилище.
        repository.save(service);
    }

    // Комментарий-описание метода.
    // Добавляет услугу по отдельным полям.

    // Это ВТОРАЯ версия перегруженного метода addService — она удобна,
    // когда у вызывающего кода ЕЩЁ НЕТ готового объекта GroomingService
    // (например, данные только что введены пользователем в отдельные поля формы),
    // и не нужно самостоятельно создавать record, чтобы вызвать этот метод —
    // сервис сам соберёт объект внутри себя (см. ниже).
    public void addService(String title, int durationMinutes, BigDecimal price, String description) {

        // Дальше идёт РУЧНАЯ проверка каждого поля по отдельности — прямо здесь,
        // а НЕ через вызов validateService(...), как в первой версии метода.
        // Причина: validateService() принимает готовый объект GroomingService,
        // а здесь объекта ЕЩЁ НЕТ — есть только отдельные "сырые" параметры,
        // из которых объект ещё предстоит собрать НИЖЕ, уже ПОСЛЕ всех проверок
        // (создавать объект ДО проверки корректности его же полей не имело бы смысла).
        // Из-за этого проверки в этом методе почти ДОСЛОВНО дублируют то, что
        // происходит внутри validateService() — это осознанный компромисс данной
        // реализации (в более "чистой" архитектуре сюда стоило бы вынести общую
        // проверку каждого отдельного поля в переиспользуемые приватные методы,
        // чтобы не повторять один и тот же код дважды).

        // title == null || title.isBlank() — проверяем И на null (переменная вообще
        // не была передана/инициализирована), И на "пустую по сути" строку
        // (isBlank() считает пустыми также строки из одних пробелов, в отличие
        // от isEmpty(), который проверяет только строки нулевой длины "").
        if (title == null || title.isBlank()) {
            // IllegalArgumentException — стандартное unchecked-исключение для
            // случая "в метод передан некорректный аргумент". Обратите внимание:
            // в отличие от репозитория (где SQLException оборачивали в
            // RuntimeException из-за ограничений контракта интерфейса), здесь
            // сервис сам, СОЗНАТЕЛЬНО выбрасывает подходящее по смыслу исключение
            // — никакого "внешнего" checked-исключения тут нет, это просто
            // ЯВНАЯ проверка бизнес-правила самим сервисом.
            throw new IllegalArgumentException("Название услуги не может быть пустым");
        }
        if (price == null) {
            throw new IllegalArgumentException("Цена не может быть пустой");
        }
        // price.compareTo(BigDecimal.ZERO) < 0 — для BigDecimal, как и в
        // GroomingAnalytics, сравнение через "<" или "<=" напрямую невозможно
        // (это не примитивный числовой тип), поэтому используется compareTo():
        // отрицательный результат означает, что "price" МЕНЬШЕ нуля (то есть
        // цена отрицательная — недопустимое значение для бизнес-логики).
        if (price.compareTo(BigDecimal.ZERO) < 0) {
            throw new IllegalArgumentException("Цена не может быть отрицательной");
        }
        // durationMinutes — примитивный int, поэтому здесь МОЖНО использовать
        // обычное сравнение "<=" (в отличие от BigDecimal выше).
        if (durationMinutes <= 0) {
            throw new IllegalArgumentException("Длительность должна быть больше 0");
        }

        // Если ВСЕ проверки выше пройдены без исключений — только теперь
        // создаём итоговый объект GroomingService из проверенных данных.
        //
        // Первый параметр — "null" вместо конкретного id: так как это НОВАЯ
        // услуга, которой ещё только предстоит быть сохранённой в базу данных,
        // настоящий id появится только ПОСЛЕ вставки (сгенерирует сама база
        // через BIGSERIAL — см. схему таблицы в DatabaseConnection).
        //
        // "title.trim()" — убираем случайные пробелы по краям введённого
        // пользователем названия (например, если пользователь случайно ввёл
        // " Стрижка " с пробелами) — так в базу попадёт "чистое" значение.
        //
        // "description == null ? "" : description.trim()" — тернарный оператор:
        // если описание вообще не передали (null), подставляем пустую строку
        // вместо null. Это важно, так как в схеме базы данных колонка description
        // объявлена как "NOT NULL" (см. DatabaseConnection) — попытка вставить
        // туда настоящий null привела бы к ошибке базы данных на уровне
        // ограничения NOT NULL. Если же описание передали, но, возможно,
        // с лишними пробелами по краям — очищаем их через .trim(), как и с title.
        GroomingService service = new GroomingService(null, title.trim(), durationMinutes, price,
                description == null ? "" : description.trim());

        // Передаём собранный и уже проверенный объект напрямую репозиторию,
        // минуя validateService() — повторная проверка тут не нужна: все условия
        // validateService() (title не пустой, price не отрицательный,
        // durationMinutes > 0) фактически уже проверены строками выше вручную.
        repository.save(service);
    }

    // Комментарий-описание метода.
    // Ищет услугу по её ID.

    // Ещё один простой метод-"обёртка" над репозиторием, аналогично
    // getAllServices() —
    // никакой дополнительной бизнес-логики здесь нет, метод просто делегирует
    // вызов репозиторию и возвращает результат Optional как есть, сохраняя
    // единую точку входа через сервисный слой.
    public Optional<GroomingService> getServiceById(Long id) {
        return repository.findById(id);
    }

    // Комментарий-описание метода.
    // Обновляет существующую услугу.

    // Возвращаемый тип "boolean" — сервис здесь просто "прокидывает наружу"
    // тот же самый boolean-результат, что вернул repository.update(...)
    // (см. комментарии к JDBC-репозиторию: true — обновление реально произошло,
    // false — услуги с таким id не существовало).
    public boolean updateService(Long id, String title, int durationMinutes, BigDecimal price, String description) {

        // "id == null || id <= 0" — здесь сначала проверяется id НА NULL,
        // и только потом (благодаря короткому замыканию оператора "||":
        // если первое условие уже true, второе не вычисляется) идёт сравнение
        // "id <= 0". Это важно и правильно: если бы порядок был обратным
        // ("id <= 0 || id == null"), при null-значении id сравнение "id <= 0"
        // попыталось бы распаковать null в примитив (так как оператор "<="
        // работает с примитивным long, а id — объектный Long) и привело бы
        // к NullPointerException ДО того, как успела бы сработать проверка на null.
        // Здесь же порядок условий выбран верно: сначала безопасная проверка
        // на null, и только потом — сравнение значения с нулём.
        if (id == null || id <= 0) {
            throw new IllegalArgumentException("ID должен быть положительным");
        }
        // Дальше — точно такой же набор проверок полей услуги, как и во второй
        // версии addService(...) выше (снова дублирование кода проверки,
        // а не переиспользование общего приватного метода — тот же архитектурный
        // компромисс, что уже отмечался в addService).
        if (title == null || title.isBlank()) {
            throw new IllegalArgumentException("Название услуги не может быть пустым");
        }
        if (price == null) {
            throw new IllegalArgumentException("Цена не может быть пустой");
        }
        if (price.compareTo(BigDecimal.ZERO) < 0) {
            throw new IllegalArgumentException("Цена не может быть отрицательной");
        }
        if (durationMinutes <= 0) {
            throw new IllegalArgumentException("Длительность должна быть больше 0");
        }

        // Создаём НОВЫЙ объект GroomingService с уже ИЗВЕСТНЫМ id (переданным
        // в параметрах метода, в отличие от addService, где id всегда null) —
        // это соответствует тому, что record неизменяем: "обновление" на уровне
        // Java-объектов означает не изменение старого объекта, а создание нового
        // с нужными значениями полей (тот же принцип обсуждался в комментариях
        // к самому record GroomingService).
        GroomingService updated = new GroomingService(id, title.trim(), durationMinutes, price,
                description == null ? "" : description.trim());

        // Передаём собранный объект репозиторию, который уже сам выполнит
        // SQL-запрос UPDATE и вернёт true/false в зависимости от того,
        // была ли реально найдена и изменена строка с таким id.
        return repository.update(updated);
    }

    // Комментарий-описание метода.
    // Удаляет услугу по ID.

    // Ещё одна простая "обёртка" над репозиторием без дополнительной логики —
    // сервис прямо передаёт id в repository.deleteById(id) и возвращает
    // его результат (true/false) без изменений.
    public boolean deleteService(Long id) {
        return repository.deleteById(id);
    }

    // Комментарий-описание метода.
    // Внутренний метод проверки корректности объекта услуги.

    // "private" — метод используется ТОЛЬКО внутри этого класса (в первой версии
    // addService(GroomingService service)) и не должен вызываться откуда-либо
    // ещё — это внутренняя техническая деталь реализации сервиса.
    // "void" — метод ничего не возвращает: его роль — либо "молча" завершиться
    // успешно (все проверки пройдены), либо бросить исключение, если что-то
    // не так. Такой стиль метода иногда называют "методом-стражем" (guard method).
    private void validateService(GroomingService service) {
        // Проверяем сначала САМ объект на null — если передан null целиком,
        // дальнейшие обращения вроде service.title() привели бы к
        // NullPointerException, поэтому эта проверка должна идти ПЕРВОЙ.
        if (service == null) {
            throw new IllegalArgumentException("Услуга не может быть null");
        }
        // Дальше — та же логика проверки отдельных полей, что и в addService(...)
        // с четырьмя параметрами и в updateService(...), только здесь поля
        // читаются через геттеры record (service.title(), service.price(),
        // service.durationMinutes()) вместо отдельных параметров метода —
        // по сути та же самая проверка, просто применённая к уже готовому объекту,
        // а не к "сырым" значениям до создания объекта.
        if (service.title() == null || service.title().isBlank()) {
            throw new IllegalArgumentException("Название услуги не может быть пустым");
        }
        if (service.price() == null) {
            throw new IllegalArgumentException("Цена не может быть пустой");
        }
        if (service.price().compareTo(BigDecimal.ZERO) < 0) {
            throw new IllegalArgumentException("Цена не может быть отрицательной");
        }
        if (service.durationMinutes() <= 0) {
            throw new IllegalArgumentException("Длительность должна быть больше 0");
        }
        // Если метод "дошёл" до этой точки, ни одно из условий выше не сработало —
        // значит, объект корректен, и метод просто завершается без явного
        // return (у void-методов конец тела метода эквивалентен "return;").
    }
}