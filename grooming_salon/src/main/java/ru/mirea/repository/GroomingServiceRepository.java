// Пакет "repository" — здесь описываются абстракции и реализации доступа
// к данным. Этот файл — как раз АБСТРАКЦИЯ (интерфейс), а не реализация:
// конкретный способ хранения данных (JDBC, JPA, список в памяти) здесь
// НИКАК не упоминается и не подразумевается — интерфейс лишь описывает,
// КАКИЕ операции должны быть доступны, а не КАК именно они выполняются.
package ru.mirea.repository;

// List — интерфейс списка, используется как возвращаемый тип метода findAll().
import java.util.List;

// Optional<T> — "обёртка" вокруг значения, которое может отсутствовать.
// Используется как возвращаемый тип findById(), чтобы сразу в сигнатуре метода
// зафиксировать: "услуга с данным id может быть не найдена — это нормальный
// исход, а не аварийная ситуация", и заставить вызывающий код явно обработать
// оба варианта (услуга найдена / не найдена), а не забыть проверку на null.
import java.util.Optional;

// Импортируем модель GroomingService — интерфейс оперирует именно объектами
// этого типа при описании своих операций (сохранить услугу, найти услугу и т.д.).
import ru.mirea.model.GroomingService;

// Комментарий-описание интерфейса.
// Интерфейс репозитория услуг.
// Он задаёт обязательные операции для работы с данными: добавление, поиск, обновление и удаление.

// "public" — интерфейс должен быть виден из ЛЮБОГО другого пакета проекта:
// и сервисному слою, который будет обращаться к репозиторию через эту абстракцию,
// и любому классу, который реализует этот интерфейс (например,
// GroomingServiceJdbcRepository из соседнего файла, а в будущем, возможно,
// GroomingServiceInMemoryRepository для тестов или GroomingServiceJpaRepository
// при переходе на Spring Data JPA).
//
// "interface" (а не "class" или "abstract class") — выбран именно интерфейс,
// потому что цель этого файла — описать ЧИСТЫЙ КОНТРАКТ ("что должно уметь
// делать любое хранилище услуг"), полностью ОТДЕЛЁННЫЙ от того, КАК конкретно
// эти операции реализованы. У интерфейса (в его базовой форме, как здесь)
// нет ни полей с состоянием, ни тела методов — только их "подписи" (сигнатуры):
// имя метода, параметры и возвращаемый тип. Это ключевое архитектурное решение
// всего проекта: сервисный слой и другой код, которому нужно работать с услугами,
// будет зависеть ИМЕННО от этого интерфейса GroomingServiceRepository,
// а не от конкретного класса вроде GroomingServiceJdbcRepository. Благодаря
// этому способ хранения данных можно поменять (например, с JDBC на JPA,
// или временно подставить "фейковую" реализацию в памяти для юнит-тестов),
// вообще не трогая код, который просто вызывает repository.save(...) или
// repository.findById(...) — он ничего не знает и не должен знать о базе
// данных, SQL-запросах и подобных деталях реализации.
//
// Такой интерфейс часто называют паттерном "Repository" — он абстрагирует
// работу с хранилищем данных за простым набором понятных операций
// (сохранить/найти/обновить/удалить), спрятав внутри себя все технические
// детали (SQL, соединения с БД, маппинг строк в объекты и т.п.).
public interface GroomingServiceRepository {

    // Комментарий-описание метода.
    // Сохраняет новую услугу.

    // У методов интерфейса НЕТ модификатора доступа, написанного явно (нет слова
    // "public" перед "void"), и это НЕ значит, что метод package-private
    // (видимый только внутри пакета), как это было бы у обычного класса без
    // модификатора. Особое правило Java для интерфейсов: ВСЕ методы интерфейса
    // (если не помечены как default, static или private) НЕЯВНО являются
    // одновременно и "public", и "abstract" — то есть у них нет реализации
    // (тела метода, только сигнатура, завершающаяся точкой с запятой вместо
    // фигурных скобок), и любой класс, реализующий этот интерфейс, ОБЯЗАН
    // сделать свою реализацию именно как public (см. соответствующий метод
    // в GroomingServiceJdbcRepository, помеченный @Override).
    //
    // Возвращаемый тип "void" — метод не возвращает результат: обязанность
    // сохранить услугу считается выполненной, если метод завершился без исключения.
    // (Заметим: сама сигнатура интерфейса НЕ объявляет никаких checked-исключений
    // через throws — поэтому, как разобрано в комментариях к JDBC-реализации,
    // ей пришлось оборачивать SQLException в RuntimeException, чтобы не нарушать
    // этот контракт интерфейса.)
    //
    // Параметр "GroomingService service" — сама услуга для сохранения, целиком
    // (включая, возможно, ещё не заполненный id — если это НОВАЯ услуга, id может
    // быть null, а конкретная реализация уже сама разберётся, как сгенерировать
    // настоящий id при вставке в хранилище).
    void save(GroomingService service);

    // Комментарий-описание метода.
    // Находит услугу по идентификатору.

    // Возвращаемый тип "Optional<GroomingService>" — контракт интерфейса ЧЕСТНО
    // предупреждает всех, кто будет им пользоваться: результат поиска МОЖЕТ
    // оказаться пустым (услуги с таким id не существует), и это не исключительная
    // ситуация, а обычный, ожидаемый результат работы метода. Любая реализация
    // этого интерфейса ОБЯЗАНА возвращать именно Optional (а не, например, null
    // напрямую или бросать исключение при "не найдено") — так гарантируется
    // единообразное поведение для ВСЕХ возможных реализаций репозитория.
    //
    // Параметр "Long id" (объектный тип, а не примитивный long) — позволяет
    // при необходимости передать null (например, если вызывающий код по ошибке
    // не указал id) — хотя в текущем контракте это явно не оговорено и не
    // обрабатывается специальным образом, конкретная реализация должна сама
    // решить, что делать в таком случае (в GroomingServiceJdbcRepository
    // передача null привела бы к NullPointerException при автоматической
    // распаковке в setLong — см. комментарии к этому файлу).
    Optional<GroomingService> findById(Long id);

    // Комментарий-описание метода.
    // Возвращает все услуги из хранилища.

    // Возвращаемый тип "List<GroomingService>" — контракт подразумевает, что
    // метод ВСЕГДА возвращает список (даже пустой, если услуг нет вообще),
    // а НЕ null — вызывающему коду не нужно отдельно проверять результат
    // findAll() на null, достаточно проверить на пустоту (isEmpty()), если это
    // важно.
    // У метода нет параметров — по контракту он возвращает АБСОЛЮТНО ВСЕ услуги,
    // без какой-либо фильтрации или пагинации (если бы в будущем понадобилась,
    // например, разбивка на страницы, в контракт интерфейса нужно было бы
    // добавить отдельные параметры или отдельный метод).
    List<GroomingService> findAll();

    // Комментарий-описание метода.
    // Обновляет уже существующую услугу.

    // Возвращаемый тип "boolean" — контракт явно требует, чтобы РЕАЛИЗАЦИЯ
    // сообщала вызывающему коду, произошло ли обновление НА САМОМ ДЕЛЕ
    // (true — строка с таким id была найдена и изменена, false — например,
    // услуги с таким id уже не существует в хранилище, обновлять было нечего).
    // Это отличается от save(), у которого тип возврата void: контракт репозитория
    // считает "успешность обновления" информацией, которая важна вызывающему коду
    // (например, чтобы решить, показывать ли пользователю сообщение об ошибке
    // "услуга не найдена"), а вот при СОХРАНЕНИИ новой услуги подобной
    // неопределённости в контракте не заложено — предполагается, что save()
    // либо успешно сохраняет услугу, либо выбрасывает исключение.
    //
    // Параметр "GroomingService service" — объект должен уже содержать
    // непустой (не null) id, по которому реализация поймёт, КАКУЮ именно
    // существующую запись нужно обновить — сам интерфейс, впрочем, не может
    // заставить вызывающий код гарантировать это на уровне типов (record
    // допускает id == null), поэтому это, по сути, часть "контракта по
    // соглашению", а не то, что может проверить компилятор.
    boolean update(GroomingService service);

    // Комментарий-описание метода.
    // Удаляет услугу по её ID.

    // Аналогично update(): возвращаемый тип "boolean" сообщает, было ли
    // что-то РЕАЛЬНО удалено (true) или услуги с таким id и так не было
    // в хранилище (false) — контракт заранее закладывает, что вызывающему
    // коду может быть важно отличить эти два случая, а не просто знать,
    // что метод "выполнился без ошибок".
    //
    // Параметр "Long id" — только идентификатор, без остальных данных услуги
    // (в отличие от update(), которому нужен весь объект целиком) — для
    // удаления достаточно знать, КАКУЮ запись убрать, а не то, какие у неё
    // сейчас значения полей.
    boolean deleteById(Long id);
}