// Пакет "repository" — сюда по смыслу помещают код, отвечающий за доступ
// к хранилищу данных (базе данных): подключение, запросы на чтение/запись.
// В отличие от "model" (описывает ЧТО хранится) и "analytics" (что с этим считать),
// "repository" отвечает за КАК данные попадают в программу и обратно в БД.
package ru.mirea.repository;

// Connection — интерфейс, представляющий ОДНО активное соединение (сессию)
// с базой данных: через него отправляются запросы и получаются результаты.
import java.sql.Connection;

// DriverManager — служебный класс JDBC, который умеет НАХОДИТЬ подходящий
// драйвер базы данных (по префиксу строки подключения, например "jdbc:postgresql:")
// и открывать через него соединение. Именно DriverManager.getConnection(...)
// фактически "разговаривает" с сервером базы данных при установке соединения.
import java.sql.DriverManager;

// ResultSet — представляет РЕЗУЛЬТАТ выполнения SQL-запроса SELECT: это как
// "курсор", который построчно проходит по полученным из базы данным.
import java.sql.ResultSet;

// SQLException — checked-исключение (проверяемое компилятором), которое
// выбрасывают практически все операции JDBC: подключение к серверу, выполнение
// запроса, чтение результата и т.д. Так как работа с базой данных зависит
// от сети, доступности сервера, корректности SQL и множества других внешних
// факторов, компилятор ОБЯЗЫВАЕТ явно обработать эту ошибку (try-catch)
// либо "передать ответственность" вызывающему коду через "throws SQLException"
// (как сделано в обоих методах этого класса ниже).
import java.sql.SQLException;

// Statement — представляет SQL-инструкцию для отправки в базу данных.
// Используется здесь БЕЗ параметров (в отличие от PreparedStatement),
// так как весь SQL в этом классе — фиксированный текст создания таблиц
// и начальных данных, без пользовательского ввода, которое нужно было бы
// безопасно подставлять через "?" (что как раз является задачей PreparedStatement).
import java.sql.Statement;

// Комментарий-описание класса.
// Класс для подключения к базе данных PostgreSQL.
// Он хранит адрес сервера, логин и пароль,
// а затем создаёт соединение для работы с БД.

// "public" — класс должен использоваться из других пакетов (например,
// из "repository"-классов конкретных сущностей типа ServiceRepository,
// AppointmentRepository, которым нужно получать соединение с БД для своих запросов).
//
// "final" — запрещает наследование от этого класса. Как и в GroomingExporter,
// это осознанное решение: класс представляет собой простой набор статических
// утилитных методов без собственного состояния (полей объекта) — расширять
// такой класс через наследование архитектурно не нужно.
public final class DatabaseConnection {

    // "private" — константа видна ТОЛЬКО внутри этого класса, снаружи адрес
    // сервера БД никому не нужен напрямую (все обращаются к базе через методы
    // этого класса, а не напрямую по URL/USER/PASSWORD).
    // "static" — константа принадлежит КЛАССУ целиком, а не отдельному объекту
    // (что логично: класс вообще не создаёт объекты — см. приватный конструктор
    // ниже,
    // и адрес сервера один и тот же для всего приложения, а не свой у каждого
    // "экземпляра").
    // "final" — значение присваивается ОДИН РАЗ и больше никогда не может
    // измениться
    // за время работы программы (в отличие от обычного поля, значение которого
    // можно менять). Комбинация "private static final" плюс имя ВСЕМИ ЗАГЛАВНЫМИ
    // буквами (URL, USER, PASSWORD) — общепринятое в Java соглашение об оформлении
    // именно КОНСТАНТ (значений, которые не меняются на протяжении всей работы
    // программы).
    //
    // Строка подключения (JDBC URL) устроена по схеме:
    // "jdbc:postgresql://адрес_сервера:порт/имя_базы_данных"
    // "jdbc:postgresql:" — префикс, по которому DriverManager понимает, что нужно
    // использовать ИМЕННО драйвер PostgreSQL (а не MySQL, Oracle и т.д.);
    // "localhost" — сервер базы данных запущен на этом же компьютере;
    // "5432" — стандартный порт, на котором PostgreSQL "слушает" входящие
    // подключения;
    // "grooming_db" — имя конкретной базы данных на сервере, к которой
    // подключаемся.
    private static final String URL = "jdbc:postgresql://localhost:5432/grooming_db";

    // Логин пользователя базы данных. "postgres" — это имя пользователя
    // "по умолчанию", которое автоматически создаётся при установке PostgreSQL.
    private static final String USER = "postgres";

    // Пароль пользователя базы данных.
    // ВАЖНОЕ ЗАМЕЧАНИЕ ПО БЕЗОПАСНОСТИ (не про сам синтаксис Java, а про подход
    // в целом): хранить логин и особенно пароль от базы данных прямо в исходном
    // коде — плохая практика для реального (боевого) приложения, так как:
    // - пароль попадает в систему контроля версий (например, в Git) и виден
    // всем, у кого есть доступ к репозиторию;
    // - при смене пароля пришлось бы менять и пересобирать сам код программы.
    // В учебном/тестовом проекте так делать допустимо для простоты, но в реальном
    // проекте такие значения обычно выносят в переменные окружения, файлы
    // конфигурации (application.properties/.yml) или специальные хранилища
    // секретов.
    private static final String PASSWORD = "1234";

    // Приватный конструктор без параметров и без тела — стандартный приём
    // для классов-утилит: запрещает создание объектов через "new
    // DatabaseConnection()",
    // так как весь класс состоит из статических методов и статических констант,
    // а значит, создавать отдельные "экземпляры" этого класса не имеет смысла.
    private DatabaseConnection() {
    }

    // Комментарий-описание метода.
    // Метод создаёт и возвращает соединение с базой данных.

    // "public" — метод вызывается ИЗВНЕ (другими классами репозитория, которым
    // нужно соединение, чтобы выполнить свои SQL-запросы).
    // "static" — вызывается через имя класса: DatabaseConnection.getConnection().
    // Возвращаемый тип "Connection" — объект открытого соединения с базой данных.
    // "throws SQLException" — метод честно предупреждает: "получение соединения
    // может завершиться ошибкой" (например, сервер недоступен, неверный
    // логин/пароль, база данных не существует) — и перекладывает обработку
    // этой ошибки на код, который ВЫЗЫВАЕТ getConnection().
    public static Connection getConnection() throws SQLException {
        // DriverManager.getConnection(URL, USER, PASSWORD) — обращается к серверу
        // базы данных по указанному адресу с указанными учётными данными
        // и, если всё прошло успешно, возвращает готовый объект Connection,
        // через который дальше можно выполнять запросы.
        // "return" сразу отдаёт результат вызывающему коду — в этом методе
        // больше ничего не происходит, он просто "прячет" детали DriverManager
        // и константы подключения за простым вызовом "getConnection()".
        return DriverManager.getConnection(URL, USER, PASSWORD);
    }

    // Комментарий-описание метода.
    // Создаёт таблицы и наполняет базу тестовыми данными, если она пустая.

    // "public static void" — метод вызывается извне, не привязан к объекту,
    // ничего не возвращает (его смысл — выполнить действия над базой данных,
    // а не вычислить и вернуть значение).
    // "throws SQLException" — как и выше, вся работа с БД может закончиться
    // ошибкой,
    // и метод передаёт ответственность за обработку вызывающему коду.
    public static void initializeDatabase() throws SQLException {

        // try-with-resources — специальная конструкция try(...), в скобках которой
        // объявляются ресурсы (объекты, реализующие интерфейс AutoCloseable),
        // которые Java гарантированно и АВТОМАТИЧЕСКИ закроет по выходу из блока
        // try — даже если внутри произойдёт исключение. Здесь два таких ресурса,
        // перечисленные через точку с запятой:
        // 1) connection = getConnection() — открытое соединение с базой данных;
        // 2) statement = connection.createStatement() — объект для отправки SQL-команд
        // через это соединение.
        // Без try-with-resources пришлось бы вручную писать блок finally
        // с явным закрытием connection.close() и statement.close(), заботясь
        // о правильном порядке закрытия и о случае, когда исключение произошло
        // ДО того, как оба ресурса успели открыться — try-with-resources берёт
        // всю эту работу на себя и закрывает ресурсы в ПРАВИЛЬНОМ порядке
        // (сначала statement, затем connection — в порядке, обратном открытию).
        try (Connection connection = getConnection();
                Statement statement = connection.createStatement()) {

            // statement.executeUpdate(...) — выполняет SQL-команду, которая
            // ИЗМЕНЯЕТ структуру или данные базы (в отличие от executeQuery(),
            // которая используется для SELECT-запросов, возвращающих данные).
            // executeUpdate() применяют и для DDL-команд (CREATE TABLE и т.п.),
            // хотя формально они не "обновляют строки" в привычном смысле —
            // для таких команд executeUpdate() просто выполняет их и возвращает 0.
            //
            // """ ... """ — текстовый блок (text block), появившийся в Java 15:
            // способ записать МНОГОСТРОЧНУЮ строку без необходимости склеивать
            // её из отдельных кусков через "+" и без экранирования переносов строк —
            // текст между тройными кавычками сохраняет свои переносы строк "как есть",
            // что удобно для длинных SQL-запросов, где важна читаемость форматирования.
            //
            // Разбор самого SQL-запроса создания таблицы grooming_services:
            // CREATE TABLE IF NOT EXISTS ... — создать таблицу, только если она
            // ЕЩЁ НЕ существует (повторный запуск метода не вызовет ошибку
            // "таблица уже существует", а просто ничего не сделает для неё);
            // id BIGSERIAL PRIMARY KEY — колонка id: BIGSERIAL — специальный тип
            // PostgreSQL, который автоматически генерирует следующее число
            // (1, 2, 3, ...) при каждой вставке новой строки (аналог
            // "автоинкремента"), PRIMARY KEY — делает эту колонку первичным
            // ключом (уникальным идентификатором строки, по которому её
            // удобно и быстро искать);
            // title VARCHAR(255) NOT NULL — текстовое поле максимум 255 символов,
            // NOT NULL означает, что это поле ОБЯЗАТЕЛЬНО должно быть заполнено
            // при вставке строки (база данных сама не даст вставить NULL сюда);
            // duration_minutes INT NOT NULL CHECK (duration_minutes > 0) — целое
            // число, обязательное, и ограничение CHECK — база данных сама
            // на своём уровне не позволит вставить значение <= 0 (это защита
            // данных НА УРОВНЕ БАЗЫ, дополнительно к любым проверкам в коде Java);
            // price DECIMAL(10, 2) NOT NULL CHECK (price >= 0) — денежный тип
            // с точностью 10 знаков всего, из которых 2 знака после запятой
            // (аналог BigDecimal на стороне базы данных — тоже для точных
            // денежных значений без ошибок округления), и запрет отрицательных
            // значений через CHECK;
            // description VARCHAR(1000) NOT NULL — описание услуги, обязательное
            // текстовое поле длиной до 1000 символов.
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS grooming_services (
                        id BIGSERIAL PRIMARY KEY,
                        title VARCHAR(255) NOT NULL,
                        duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
                        price DECIMAL(10, 2) NOT NULL CHECK (price >= 0),
                        description VARCHAR(1000) NOT NULL
                    )
                    """);

            // Второй запрос — создание таблицы appointments (записи на приём).
            // Разбор новых для этой таблицы моментов:
            // client_name / pet_name VARCHAR(255) NOT NULL — обязательные строки,
            // как и в предыдущей таблице;
            // service_id BIGINT NOT NULL REFERENCES grooming_services(id) ON DELETE CASCADE
            // — это ВНЕШНИЙ КЛЮЧ (foreign key): значение в этой колонке ОБЯЗАНО
            // совпадать с каким-то реально существующим id из таблицы
            // grooming_services (база данных сама не позволит вставить запись
            // с несуществующим service_id — это гарантирует целостность связи
            // между таблицами на уровне самой БД, а не только в коде Java).
            // "ON DELETE CASCADE" означает: если удалить услугу из
            // grooming_services, то ВСЕ связанные с ней записи на приём
            // в appointments будут удалены АВТОМАТИЧЕСКИ базой данных
            // (каскадное удаление) — то есть не останется "осиротевших"
            // записей, ссылающихся на несуществующую услугу;
            // booking_code VARCHAR(50) NOT NULL UNIQUE — код бронирования
            // обязателен, и UNIQUE означает, что база данных не позволит
            // сохранить ДВЕ разные записи с одинаковым booking_code —
            // гарантия уникальности на уровне БД;
            // status VARCHAR(50) NOT NULL DEFAULT 'NEW' — статус обязателен,
            // но если при вставке строки его явно не указать, база данных
            // САМА подставит значение по умолчанию — строку 'NEW'
            // (это соответствует record Appointment из модели, где поле
            // status тоже хранится как обычная строка).
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS appointments (
                        id BIGSERIAL PRIMARY KEY,
                        client_name VARCHAR(255) NOT NULL,
                        pet_name VARCHAR(255) NOT NULL,
                        service_id BIGINT NOT NULL REFERENCES grooming_services(id) ON DELETE CASCADE,
                        booking_code VARCHAR(50) NOT NULL UNIQUE,
                        status VARCHAR(50) NOT NULL DEFAULT 'NEW'
                    )
                    """);

            // Вложенный try-with-resources — отдельный ресурс ResultSet, который
            // возвращает executeQuery() (в отличие от executeUpdate() выше,
            // здесь используется executeQuery(), так как SELECT COUNT(*) — это
            // запрос НА ЧТЕНИЕ данных, а не на изменение структуры/данных).
            // ResultSet тоже реализует AutoCloseable и должен быть закрыт после
            // использования, поэтому он тоже обёрнут в try-with-resources —
            // отдельно от внешнего try, так как нужен только на время этой проверки,
            // а не на весь метод целиком.
            //
            // "SELECT COUNT(*) FROM grooming_services" — SQL-запрос, который
            // возвращает ОДНО число: сколько всего строк сейчас в таблице услуг.
            try (ResultSet resultSet = statement.executeQuery("SELECT COUNT(*) FROM grooming_services")) {

                // resultSet.next() — переводит курсор ResultSet на следующую
                // (в данном случае — первую и единственную) строку результата
                // и возвращает true, если такая строка есть. Для SELECT COUNT(*)
                // результат всегда содержит РОВНО одну строку с одним числом,
                // поэтому next() практически всегда вернёт true (проверка на всякий
                // случай — если результат вообще пуст, next() вернёт false).
                //
                // resultSet.getInt(1) — читает значение из результата как int.
                // Число "1" здесь — это НЕ индекс с нуля (как в массивах Java),
                // а номер СТОЛБЦА результата, начиная с 1 (особенность именно JDBC:
                // нумерация столбцов ResultSet всегда начинается с единицы, а не с нуля).
                // Так как в запросе только один столбец (результат COUNT(*)),
                // используется getInt(1) — "значение из первого (и единственного) столбца".
                //
                // Условие в целом: "resultSet.next() && resultSet.getInt(1) == 0" —
                // "если в результате есть строка И количество услуг равно нулю" —
                // то есть таблица grooming_services пока пустая (например,
                // сразу после того, как её только что создали строкой выше).
                // "&&" — логическое И с "коротким замыканием": если resultSet.next()
                // вернёт false, вторая часть (resultSet.getInt(1)) вообще не будет
                // вычисляться — что важно, так как вызывать getInt() без успешного
                // next() было бы ошибкой (курсор не указывал бы ни на какую строку).
                if (resultSet.next() && resultSet.getInt(1) == 0) {

                    // Если услуг в базе ещё нет — сразу вставляем 5 "стартовых"
                    // (тестовых/демонстрационных) услуг одним SQL-запросом.
                    // Синтаксис "INSERT INTO ... VALUES (...), (...), (...), ...;"
                    // — это ОДНА команда INSERT с НЕСКОЛЬКИМИ наборами значений
                    // через запятую, что вставляет сразу несколько строк
                    // за один запрос к базе данных (эффективнее, чем делать
                    // пять отдельных вызовов executeUpdate() с одним INSERT в каждом).
                    // Строковые значения (title, description) обёрнуты в одинарные
                    // кавычки — это синтаксис самого SQL (а не Java) для текстовых
                    // литералов внутри SQL-запроса.
                    //
                    // ВАЖНОЕ ЗАМЕЧАНИЕ по безопасности (снова не про синтаксис,
                    // а про подход): здесь текст SQL-запроса — ПОЛНОСТЬЮ фиксированный,
                    // "зашитый" прямо в коде, без каких-либо значений от пользователя,
                    // поэтому использование простого Statement (а не PreparedStatement)
                    // безопасно. Если бы значения (например, title) приходили от
                    // пользователя (из формы ввода), тогда ОБЯЗАТЕЛЬНО следовало бы
                    // использовать PreparedStatement с параметрами "?" вместо прямой
                    // подстановки текста в SQL-строку — иначе возникает уязвимость
                    // SQL-инъекции (когда пользователь мог бы вставить в поле ввода
                    // не просто текст, а часть вредоносного SQL-кода).
                    statement.executeUpdate(
                            """
                                    INSERT INTO grooming_services (title, duration_minutes, price, description) VALUES
                                    ('Комплекс для собак мелких пород', 90, 2500.00, 'Купание, сушка, гигиеническая стрижка, стрижка когтей, чистка ушей'),
                                    ('Комплекс для собак крупных пород', 120, 4200.00, 'Вычесывание, глубокая очистка шерсти, стрижка по стандарту породы, уход за когтями'),
                                    ('Экспресс-линька для кошек', 60, 2100.00, 'Удаление отмершего подшерстка специализированным инструментом, купание и сушка'),
                                    ('Гигиенический уход', 30, 1000.00, 'Подрезание когтей, обработка подушечек лап и гигиеническая чистка ушных раковин'),
                                    ('Стрижка кошек (без мытья)', 45, 1800.00, 'Модельная или гигиеническая стрижка машинкой без водных процедур')
                                    """);
                }
                // Закрывающая скобка внутреннего try-with-resources — здесь ResultSet
                // автоматически закрывается Java, даже если бы внутри блока
                // произошло исключение.
            }
            // Закрывающая скобка внешнего try-with-resources — здесь автоматически
            // закрываются, в правильном порядке, сначала Statement, затем Connection.
        }
    }
}