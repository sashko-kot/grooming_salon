// Пакет "ui" — здесь располагают СЛОЙ ПОЛЬЗОВАТЕЛЬСКОГО ИНТЕРФЕЙСА приложения:
// код, который отвечает ТОЛЬКО за отображение меню, чтение ввода пользователя
// через консоль и вывод результатов на экран. Этот слой НЕ содержит бизнес-логики
// проверки данных (это работа сервисного слоя, "service") и НЕ работает
// напрямую с базой данных (это работа "repository") — он лишь ОБЩАЕТСЯ
// с сервисом, передавая ему "сырые" данные пользователя и показывая
// пользователю то, что сервис вернул или на что пожаловался (через исключение).
package ru.mirea.ui;

// Импортируем класс аналитики — используется здесь для дополнительных пунктов
// меню (средняя цена, самая долгая услуга, группировка, поиск, фильтрация
// по цене), которые сами по себе не являются CRUD-операциями и поэтому
// вынесены в отдельный класс, а не в GroomingServiceService.
import ru.mirea.analytics.GroomingAnalytics;

// Импортируем модель услуги — UI работает с объектами GroomingService только
// для того, чтобы прочитать их поля (через геттеры record) и вывести на экран;
// сам UI никогда не создаёт и не изменяет эти объекты напрямую.
import ru.mirea.model.GroomingService;

// Импортируем сервис — это ЕДИНСТВЕННАЯ точка входа, через которую UI-слой
// обращается к бизнес-логике и данным. UI ничего не знает о репозитории
// и о базе данных — все обращения идут строго через service.
import ru.mirea.service.GroomingServiceService;

// BigDecimal — используется здесь как тип параметра при чтении цены
// от пользователя (readMoney) и при передаче цены в методы аналитики.
import java.math.BigDecimal;

// List — тип, в котором сервис и аналитика возвращают наборы услуг.
import java.util.List;

// Map — используется для результата группировки услуг по длительности
// (см. showAnalytics(): категория группы -> список услуг в ней).
import java.util.Map;

// Optional — "обёртка" для результата поиска услуги по id, который может
// как найтись, так и отсутствовать; используется в findById/updateService/
// deleteService.
import java.util.Optional;

// Scanner — стандартный класс для чтения текста, введённого пользователем
// в консоли. Он не создаётся внутри этого класса, а передаётся СНАРУЖИ
// в метод show(scanner) — это позволяет использовать ОДИН и тот же Scanner
// (и, соответственно, один поток ввода System.in) во всех частях приложения,
// не открывая несколько независимых Scanner поверх одного и того же System.in
// (что могло бы привести к путанице при чтении ввода).
import java.util.Scanner;

// "public" — класс должен быть виден и вызываться извне пакета ui, например
// из главного меню приложения (там, где решается, какой раздел UI показать
// пользователю: административный, клиентский и т.д.).
//
// "class" — это объект СО СВОИМ ПОВЕДЕНИЕМ (методы, которые печатают меню,
// читают ввод, вызывают сервис), а не просто контейнер данных, поэтому
// record здесь не подходит; и не абстрактный контракт, поэтому интерфейс
// тоже не подходит.
public class AdminMenuUI {

    // "private final" — оба поля устанавливаются один раз при создании объекта
    // AdminMenuUI (в конструкторе) и больше никогда не переприсваиваются,
    // а также недоступны напрямую снаружи класса — весь доступ к бизнес-логике
    // и аналитике идёт только через методы этого класса.

    // Ссылка на сервисный слой — через него UI выполняет все операции
    // с услугами (добавление, поиск, обновление, удаление), не зная деталей
    // проверки данных или хранения в базе.
    private final GroomingServiceService service;

    // Ссылка на класс аналитики — используется для операций, которые
    // не являются простым CRUD (создание/чтение/обновление/удаление),
    // а представляют собой вычисления и обработку УЖЕ ПОЛУЧЕННОГО от сервиса
    // списка услуг (средняя цена, самая долгая услуга, группировка,
    // поиск по ключевому слову, фильтрация по цене).
    private final GroomingAnalytics analytics;

    // Комментарий-описание конструктора.
    // Создаёт UI администратора, получая сервис снаружи (внедрение зависимости),
    // а аналитику создаёт самостоятельно внутри.

    // "public" — конструктор вызывается извне (например, из главного меню
    // приложения), чтобы создать экран администратора, передав ему уже готовый
    // и настроенный объект сервиса.
    //
    // Обратите внимание на АСИММЕТРИЮ по сравнению с GroomingServiceService:
    // там репозиторий передавался СНАРУЖИ через конструктор (dependency
    // injection), а здесь GroomingAnalytics создаётся "на месте", через
    // "new GroomingAnalytics()" прямо в теле конструктора, а не принимается
    // как параметр. Это осознанное упрощение: GroomingAnalytics, судя по всему,
    // не имеет собственного состояния и зависимостей (в отличие от репозитория,
    // которому нужны логин/пароль/URL для подключения к базе), поэтому
    // создавать его "на лету" внутри UI не создаёт таких же проблем
    // с тестируемостью и гибкостью, какие обсуждались для репозитория
    // в сервисном слое. Тем не менее, с точки зрения единообразия архитектуры,
    // можно было бы точно так же принимать GroomingAnalytics параметром
    // конструктора — это архитектурный нюанс, который стоит уметь обсудить.
    public AdminMenuUI(GroomingServiceService service) {
        // "this.service" — обращение к полю класса, чтобы отличить его
        // от параметра конструктора с тем же именем "service"
        // (та же причина, что и "this.repository" в сервисном слое).
        this.service = service;
        // Аналитика создаётся здесь же, а не передаётся параметром —
        // см. пояснение выше.
        this.analytics = new GroomingAnalytics();
    }

    // Комментарий-описание метода.
    // Показывает главное меню администратора и обрабатывает выбор пользователя
    // в бесконечном цикле, пока пользователь не выберет выход (пункт "0").

    // "public" — метод вызывается извне (из более общего меню приложения),
    // когда пользователь выбирает раздел "администратор".
    // "void" — метод ничего не возвращает: он полностью управляет процессом
    // взаимодействия с пользователем сам, через System.out и Scanner,
    // и завершает свою работу только когда пользователь явно попросит
    // вернуться назад.
    public void show(Scanner scanner) {
        // "while (true)" — бесконечный цикл: меню должно показываться
        // ПОВТОРНО после каждого действия пользователя (добавил услугу —
        // снова видит меню, ошибся вводом — снова видит меню и так далее),
        // а не завершаться после одного выбора. Единственный способ выйти
        // из этого цикла — оператор "return" внутри ветки case "0" ниже
        // (никакого отдельного булевого флага "работает ли меню" не заводится,
        // возврат из метода сам естественным образом останавливает цикл).
        while (true) {
            // Печатаем заголовок и все пункты меню — просто текстовый вывод,
            // без какой-либо логики.
            System.out.println("\n=== ПАНЕЛЬ АДМИНИСТРАТОРА ===");
            System.out.println("1. Добавить услугу");
            System.out.println("2. Показать все услуги");
            System.out.println("3. Найти услугу по ID");
            System.out.println("4. Изменить услугу");
            System.out.println("5. Удалить услугу");
            System.out.println("6. Аналитика (средняя цена, самая долгая услуга, группировка)");
            System.out.println("7. Поиск услуг по ключевому слову");
            System.out.println("8. Показать услуги дешевле заданной цены");
            System.out.println("0. Назад");
            // "print", а не "println" — приглашение к вводу должно остаться
            // на той же строке, где пользователь начнёт печатать ответ,
            // без перевода строки после текста.
            System.out.print("Выберите действие: ");

            // "scanner.nextLine()" — читаем ВСЮ строку, введённую пользователем
            // (а не отдельное число через nextInt(), которое могло бы оставить
            // в буфере необработанный символ перевода строки и создать
            // трудноуловимую ошибку при следующем чтении).
            // ".trim()" — убираем случайные пробелы по краям (например,
            // если пользователь случайно нажал пробел перед вводом цифры),
            // чтобы сравнение с "1", "2" и т.д. в блоке switch было надёжным.
            //
            // "switch (...) { case "1" -> ...; ... }" — это СОВРЕМЕННЫЙ
            // синтаксис switch-выражения/оператора с использованием стрелок "->"
            // (появился в Java 14+), который заменяет старый, более
            // многословный синтаксис с "case "1": ... break;". Стрелочная форма
            // не требует явного "break" после каждой ветки — здесь нет риска
            // случайного "провала" (fall-through) в следующую ветку, чего легко
            // было бы допустить в старом синтаксисе, забыв поставить "break".
            switch (scanner.nextLine().trim()) {
                // Каждая ветка вызывает соответствующий приватный метод-обработчик,
                // передавая ему тот же scanner, чтобы обработчик мог сам
                // дочитать дополнительные данные, если они нужны (например,
                // для добавления услуги нужно прочитать ещё несколько строк
                // с названием, длительностью, ценой и описанием).
                case "1" -> addService(scanner);
                case "2" -> printAll();
                case "3" -> findById(scanner);
                case "4" -> updateService(scanner);
                case "5" -> deleteService(scanner);
                case "6" -> showAnalytics();
                case "7" -> searchByKeyword(scanner);
                case "8" -> findCheaperThan(scanner);
                // "{ return; }" — тело ветки взято в фигурные скобки, потому что
                // внутри нужен именно ОПЕРАТОР (return), а не одно выражение —
                // синтаксис стрелочного case требует блока {}, если внутри
                // не простое выражение-значение. "return" здесь завершает
                // весь метод show(...) целиком, а значит и его бесконечный
                // цикл while(true) — именно так пользователь "выходит в меню
                // уровнем выше".
                case "0" -> {
                    return;
                }
                // "default" — обрабатывает любой ввод, не совпавший ни с одним
                // из пунктов меню (например, если пользователь ошибся и ввёл
                // "9" или буквы) — печатаем сообщение об ошибке и НЕ прерываем
                // цикл, снова показывая меню на следующей итерации while(true).
                default -> System.out.println("Ошибка: неверный пункт меню.");
            }
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "6": считает и печатает аналитику по всем услугам
    // (среднюю цену, самую долгую услугу и группировку по длительности).

    // "private" — метод вызывается только изнутри этого класса, из show(...),
    // и не должен быть виден снаружи — это внутренняя деталь реализации меню.
    private void showAnalytics() {
        // Оборачиваем всю логику метода в try/catch — как аналитика
        // (при некорректных данных), так и сам сервис (service.getAllServices())
        // теоретически могут выбросить RuntimeException (например, если что-то
        // пошло не так при обращении к базе данных внутри репозитория) —
        // в UI-слое такие исключения не должны "уронить" всё приложение,
        // а должны быть аккуратно показаны пользователю как текстовое сообщение
        // об ошибке, после чего меню продолжит работать (цикл в show(...)
        // покажет меню заново).
        try {
            // Получаем полный список услуг ОДИН раз и переиспользуем его
            // ниже для всех видов аналитики — это эффективнее, чем вызывать
            // service.getAllServices() заново для каждого вида расчёта.
            List<GroomingService> services = service.getAllServices();
            // Если услуг вообще нет, аналитика (например, вычисление средней
            // цены) не имела бы смысла или могла бы привести к ошибке деления
            // на ноль — поэтому проверяем этот случай отдельно и сразу выходим
            // из метода, ничего больше не считая.
            if (services.isEmpty()) {
                System.out.println("Нет данных для анализа.");
                return;
            }

            System.out.println("\n--- АНАЛИТИКА ---");
            // Считаем среднюю цену через класс аналитики и сразу печатаем
            // результат, "склеивая" строки через "+" — простая конкатенация
            // текста и числового результата.
            System.out.println("Средняя стоимость услуги: " + analytics.calculateAveragePrice(services) + " руб.");

            // Получаем услугу с наибольшей длительностью.
            GroomingService longest = analytics.getLongestService(services);
            // Проверка "longest != null" — на случай, если analytics.getLongestService
            // может вернуть null (например, при пустом списке — хотя этот случай
            // уже отсечён проверкой isEmpty() выше, дополнительная проверка здесь
            // делает код более защищённым от изменений в будущем, если, скажем,
            // логика проверки пустоты списка в этом методе когда-либо изменится).
            if (longest != null) {
                System.out.println("Самая долгая услуга: " + longest.title()
                        + " (" + longest.durationMinutes() + " мин, " + longest.price() + " руб.)");
            }

            System.out.println("\n--- Группировка по длительности ---");
            // Группируем услуги по длительности — результат: Map, где ключ —
            // название категории длительности (строка, например "короткие",
            // "длинные" — конкретные категории определяются внутри
            // GroomingAnalytics), а значение — список услуг, попавших
            // в эту категорию.
            Map<String, List<GroomingService>> grouped = analytics.groupByDuration(services);
            // "grouped.forEach((category, list) -> { ... })" — метод forEach
            // интерфейса Map принимает "потребителя" с ДВУМЯ аргументами
            // (ключ и значение) и вызывает переданную лямбду для КАЖДОЙ пары
            // ключ-значение в Map, по очереди. Это более компактная замена
            // обычному циклу "for (Map.Entry<...> entry : grouped.entrySet())".
            grouped.forEach((category, list) -> {
                // Печатаем название категории как заголовок группы.
                System.out.println(category + ":");
                // "list.forEach(s -> ...)" — здесь forEach вызывается уже
                // на List (а не на Map), поэтому лямбда принимает ОДИН аргумент —
                // саму услугу "s". Для каждой услуги в группе печатаем строку
                // с отступом (" - "), чтобы визуально показать, что это
                // элемент группы, а не заголовок.
                list.forEach(s -> System.out.println("  - " + s.title() + " (" + s.durationMinutes() + " мин)"));
            });

        } catch (RuntimeException e) {
            // "e.getMessage()" — выводим пользователю только текст сообщения
            // исключения (например, "Список услуг пуст" или сообщение об ошибке
            // подключения к базе), а не всё содержимое исключения целиком
            // (стек вызовов и т.д.), так как это UI для конечного пользователя,
            // а не отладочный лог для разработчика.
            System.out.println("Ошибка аналитики: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "7": ищет услуги, в названии/описании которых
    // встречается ключевое слово, введённое пользователем.
    private void searchByKeyword(Scanner scanner) {
        try {
            // "InputHelper.readRequiredString(...)" — судя по названию,
            // это статический вспомогательный метод отдельного класса
            // InputHelper (не показан в этом файле), который читает строку
            // от пользователя и гарантирует, что она не пустая (иначе,
            // скорее всего, просит ввести значение повторно или бросает
            // исключение) — сам AdminMenuUI не занимается проверкой ввода
            // "вручную" через if, а делегирует эту техническую работу
            // отдельному вспомогательному классу, чтобы не дублировать
            // одинаковый код чтения-и-проверки строки в каждом методе меню.
            String keyword = InputHelper.readRequiredString(scanner, "Введите ключевое слово: ");
            // Передаём в аналитику СВЕЖИЙ список всех услуг (полученный прямо
            // здесь через service.getAllServices()) вместе с ключевым словом —
            // аналитика сама фильтрует список и возвращает только подходящие
            // услуги.
            List<GroomingService> found = analytics.searchByKeyword(service.getAllServices(), keyword);
            if (found.isEmpty()) {
                System.out.println("Ничего не найдено.");
            } else {
                // Сообщаем количество найденных услуг, а затем печатаем сам
                // список через общий вспомогательный метод printServices(...)
                // (см. ниже) — тот же метод, что используется и для вывода
                // ПОЛНОГО списка услуг в printAll(), что избавляет от дублирования
                // кода форматирования таблицы.
                System.out.println("Найдено услуг: " + found.size());
                printServices(found);
            }
        } catch (RuntimeException e) {
            System.out.println("Ошибка поиска: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "8": показывает услуги дешевле цены, введённой
    // пользователем, отсортированные по возрастанию цены.
    private void findCheaperThan(Scanner scanner) {
        try {
            // "InputHelper.readMoney(...)" — ещё один вспомогательный метод,
            // который читает от пользователя денежную сумму и, видимо, сам
            // проверяет, что введённое значение действительно является
            // корректным числом (и, возможно, неотрицательным) — аналогично
            // readRequiredString, вся техническая рутина чтения-и-проверки
            // конкретного типа ввода вынесена в InputHelper, а не повторяется
            // в каждом методе AdminMenuUI.
            BigDecimal maxPrice = InputHelper.readMoney(scanner, "Максимальная цена (руб): ");
            // Аналитика сама фильтрует список услуг по цене и сортирует
            // результат — UI не занимается ни фильтрацией, ни сортировкой
            // самостоятельно, а только выводит уже готовый результат.
            List<GroomingService> cheap = analytics.findServicesCheaperThan(service.getAllServices(), maxPrice);
            if (cheap.isEmpty()) {
                System.out.println("Нет услуг дешевле " + maxPrice + " руб.");
            } else {
                System.out.println("Услуги дешевле " + maxPrice + " руб. (отсортированы по цене):");
                printServices(cheap);
            }
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "1": последовательно спрашивает у пользователя
    // все поля новой услуги и передаёт их сервису для проверки и сохранения.
    private void addService(Scanner scanner) {
        try {
            // Читаем поля новой услуги по одному, каждое — своим
            // специализированным методом InputHelper, соответствующим типу
            // и правилам конкретного поля:
            // - readRequiredString — для непустого текста (название, описание);
            // - readInt(scanner, prompt, 1) — для целого числа с минимальным
            // допустимым значением 1 (длительность не может быть меньше
            // 1 минуты уже на уровне ввода, до того как значение вообще
            // попадёт в сервис);
            // - readMoney — для денежной суммы.
            //
            // Обратите внимание: часть проверок (например, "длительность >= 1"
            // через параметр readInt) происходит уже здесь, в UI-слое, ЕЩЁ ДО
            // вызова service.addService(...) — то есть некорректный ввод может
            // быть отклонён (и запрошен повторно) прямо на этапе чтения,
            // а сервис затем ВСЁ РАВНО повторно проверяет те же самые условия
            // (title не пустой, price не отрицательный, durationMinutes > 0) —
            // это намеренное дублирование проверок на двух уровнях: UI проверяет
            // формат и базовую корректность ввода для удобства пользователя
            // (быстрая обратная связь без похода "туда и обратно" через сервис),
            // а сервис проверяет то же самое ещё раз, потому что не может
            // "доверять" тому, что его вызовут именно из этого конкретного
            // класса UI — сервис обязан оставаться корректным независимо
            // от того, кто и как его вызывает (например, из другого UI
            // или из автоматических тестов, где такой предварительной проверки
            // ввода могло и не быть).
            String title = InputHelper.readRequiredString(scanner, "Название услуги: ");
            int duration = InputHelper.readInt(scanner, "Длительность (мин): ", 1);
            BigDecimal price = InputHelper.readMoney(scanner, "Стоимость (руб): ");
            String description = InputHelper.readRequiredString(scanner, "Описание: ");
            // Вызываем ПЕРЕГРУЖЕННУЮ версию addService с четырьмя отдельными
            // параметрами (а не версию с готовым объектом GroomingService) —
            // именно для таких случаев, когда данные только что введены
            // пользователем по отдельности, эта версия и предусмотрена
            // в сервисном слое.
            service.addService(title, duration, price, description);
            System.out.println("Услуга успешно добавлена.");
        } catch (RuntimeException e) {
            // Сюда попадёт, например, IllegalArgumentException, которое
            // сервис бросит, если, несмотря на предварительную проверку
            // в InputHelper, какое-то из условий всё-таки не выполнено
            // (или если readInt/readMoney по какой-то причине пропустили
            // некорректное значение) — пользователь увидит понятное сообщение
            // об ошибке, а не техническую трассировку исключения.
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "2": получает от сервиса полный список услуг
    // и печатает его в виде таблицы.
    private void printAll() {
        try {
            List<GroomingService> services = service.getAllServices();
            // Делегируем непосредственно форматирование и печать общему
            // вспомогательному методу printServices(...), который умеет
            // печатать ЛЮБОЙ список услуг (полный, отфильтрованный по цене,
            // найденный по ключевому слову и т.д.) — единая точка форматирования
            // таблицы во всём классе.
            printServices(services);
        } catch (RuntimeException e) {
            System.out.println("Ошибка при получении услуг: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "3": ищет одну услугу по ID, введённому
    // пользователем, и печатает её подробную карточку.
    private void findById(Scanner scanner) {
        // "InputHelper.readLong(scanner, prompt, 1)" — читает от пользователя
        // целое число типа long с минимальным допустимым значением 1
        // (id услуги не может быть меньше 1) — вызывается ДО try/catch,
        // так как сам процесс чтения корректного числа не требует обработки
        // RuntimeException от сервиса (эта строка либо успешно вернёт
        // корректное значение, либо сама разберётся с некорректным вводом
        // внутри InputHelper, вероятно, попросив ввести значение заново).
        long id = InputHelper.readLong(scanner, "Введите ID услуги: ", 1);
        try {
            // Ищем услугу через сервис — результат обёрнут в Optional, так как
            // услуги с таким id может не существовать.
            Optional<GroomingService> result = service.getServiceById(id);
            // "result.ifPresentOrElse(consumer, runnable)" — метод Optional,
            // принимающий ДВА "плана действий": первый выполняется, ЕСЛИ
            // значение присутствует (получает его как аргумент), второй —
            // ЕСЛИ значение отсутствует (не принимает аргументов). Это более
            // компактная альтернатива ручной проверке
            // "if (result.isPresent()) { ... } else { ... }".
            //
            // "this::printService" — ссылка на метод (method reference):
            // если услуга найдена, будет вызван this.printService(найденнаяУслуга) —
            // синтаксис "класс::метод" здесь эквивалентен написанию лямбды
            // "s -> printService(s)", но короче.
            result.ifPresentOrElse(
                    this::printService,
                    () -> System.out.println("Услуга с ID " + id + " не найдена."));
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "4": находит существующую услугу, показывает
    // её текущие данные, затем запрашивает новые значения полей и просит
    // сервис обновить услугу.
    private void updateService(Scanner scanner) {
        long id = InputHelper.readLong(scanner, "Введите ID услуги: ", 1);
        try {
            // Сначала проверяем, СУЩЕСТВУЕТ ли услуга с таким id, и только
            // если она есть — идём дальше и запрашиваем новые данные.
            // Это удобнее для пользователя, чем сразу просить ввести четыре
            // новых значения, а потом узнать, что услуги с таким id вообще
            // не было (и весь введённый текст оказался бы бесполезным).
            Optional<GroomingService> existing = service.getServiceById(id);
            if (existing.isEmpty()) {
                System.out.println("Услуга с таким ID не найдена.");
                // Явный return — прерываем метод здесь, дальше по коду идти
                // незачем, раз обновлять нечего.
                return;
            }
            System.out.println("Текущие данные:");
            // "existing.get()" — здесь безопасно вызывать get() без
            // дополнительной проверки isPresent(), так как строкой выше
            // мы уже убедились через "existing.isEmpty()", что значение
            // ТОЧНО присутствует (иначе метод уже завершился бы по return).
            printService(existing.get());
            // Запрашиваем новые значения для ВСЕХ полей услуги (не только
            // тех, что пользователь хочет изменить) — то есть интерфейс
            // не поддерживает частичное обновление отдельных полей,
            // а всегда просит ввести полностью новый набор данных.
            String title = InputHelper.readRequiredString(scanner, "Новое название: ");
            int duration = InputHelper.readInt(scanner, "Новая длительность (мин): ", 1);
            BigDecimal price = InputHelper.readMoney(scanner, "Новая стоимость (руб): ");
            String description = InputHelper.readRequiredString(scanner, "Новое описание: ");
            // Вызываем сервис, который сам заново проверит корректность полей
            // и вернёт true/false в зависимости от того, была ли услуга
            // реально найдена и обновлена в базе (см. подробности в
            // GroomingServiceService.updateService).
            boolean updated = service.updateService(id, title, duration, price, description);
            // Тернарный оператор "condition ? valueIfTrue : valueIfFalse" —
            // компактный способ выбрать одну из двух строк для печати
            // в зависимости от результата обновления.
            System.out.println(updated ? "Услуга успешно изменена." : "Услуга не была изменена.");
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "5": находит услугу по id, показывает её данные,
    // спрашивает подтверждение и только после согласия пользователя удаляет её.
    private void deleteService(Scanner scanner) {
        long id = InputHelper.readLong(scanner, "Введите ID услуги: ", 1);
        try {
            // Так же, как и в updateService(...), сначала убеждаемся, что
            // услуга существует, прежде чем вообще спрашивать пользователя
            // о подтверждении удаления — нет смысла спрашивать "удалить эту
            // услугу?", если такой услуги и так нет.
            Optional<GroomingService> existing = service.getServiceById(id);
            if (existing.isEmpty()) {
                System.out.println("Услуга с таким ID не найдена.");
                return;
            }
            // Показываем пользователю полную карточку услуги перед удалением —
            // это даёт ему возможность убедиться, что он собирается удалить
            // именно ту услугу, которую имел в виду (по названию и цене,
            // а не только по числовому id, который легко перепутать).
            printService(existing.get());
            // "InputHelper.readYesNo(scanner, question)" — ещё один
            // специализированный метод InputHelper, читающий ответ пользователя
            // и превращающий его в boolean (да/нет) — судя по всему, сам
            // разбирает разные варианты ввода ("да", "y", "нет" и т.п.).
            if (!InputHelper.readYesNo(scanner, "Удалить эту услугу?")) {
                // Пользователь передумал — отменяем операцию и НЕ вызываем
                // service.deleteService(id).
                System.out.println("Удаление отменено.");
                return;
            }
            // Только теперь, после явного подтверждения, реально вызываем
            // удаление через сервис и сообщаем результат — тернарный оператор
            // выбирает подходящий текст в зависимости от того, вернул ли
            // сервис true (услуга была удалена) или false (по какой-то причине
            // услуги с таким id уже не оказалось, например, если её удалили
            // "параллельно" из другого места приложения между проверкой
            // существования и самим удалением).
            System.out.println(service.deleteService(id) ? "Услуга удалена." : "Услуга не найдена.");
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Печатает список услуг в виде выровненной текстовой таблицы с колонками
    // ID, Название, Мин (длительность), Цена, Описание.

    // "private" — используется только внутри этого класса, вызывается
    // из нескольких мест (printAll, searchByKeyword, findCheaperThan) —
    // вынесение форматирования таблицы в один общий метод избавляет
    // от дублирования кода печати в каждом из этих мест.
    private void printServices(List<GroomingService> services) {
        // Отдельно обрабатываем случай пустого списка — печатаем понятное
        // сообщение вместо пустой таблицы из одних заголовков без единой
        // строки данных.
        if (services.isEmpty()) {
            System.out.println("Список услуг пуст.");
            return;
        }
        // "System.out.printf(...)" — печать с ФОРМАТИРОВАНИЕМ (аналог printf
        // из языка C): каждый спецификатор вида "%-4s" означает "текстовое
        // значение (s), выровненное ПО ЛЕВОМУ краю (минус перед числом),
        // в поле шириной минимум 4 символа" — если значение короче, оно
        // дополняется пробелами справа, чтобы колонки в разных строках
        // таблицы совпадали по ширине и получалось аккуратное выравнивание.
        // "%n" в конце — переносит строку способом, независимым от операционной
        // системы (в отличие от жёстко прописанного "\n"), что является более
        // правильной практикой конкретно для printf-подобных методов.
        System.out.printf("%-4s | %-34s | %-12s | %-10s | %s%n", "ID", "Название", "Мин", "Цена", "Описание");
        // "-".repeat(110) — создаёт строку из 110 символов дефиса подряд,
        // используется как визуальная разделительная линия под заголовком
        // таблицы (метод repeat() у String доступен начиная с Java 11).
        System.out.println("-".repeat(110));
        // Обычный "for-each" цикл по списку услуг — для каждой услуги печатаем
        // одну строку таблицы теми же спецификаторами форматирования, что
        // и в заголовке (важно, чтобы ширины полей совпадали, иначе колонки
        // "поплывут" и перестанут быть выровненными).
        for (GroomingService s : services) {
            // "cut(s.title(), 34)" и "cut(s.description(), 45)" — обрезаем
            // слишком длинные значения через приватный вспомогательный метод
            // cut(...) (см. ниже), чтобы длинное название или описание
            // не "разваливало" выравнивание таблицы, выходя за пределы
            // отведённой для колонки ширины. Числовые и денежные поля
            // (s.durationMinutes(), s.price()) не обрезаются, так как обычно
            // они и так короткие и умещаются в отведённую ширину.
            System.out.printf("%-4d | %-34s | %-12d | %-10s | %s%n",
                    s.id(), cut(s.title(), 34), s.durationMinutes(), s.price(), cut(s.description(), 45));
        }
    }

    // Комментарий-описание метода.
    // Печатает подробную "карточку" одной услуги — каждое поле на отдельной
    // строке, в отличие от компактной таблицы в printServices(...).

    // Используется там, где нужно показать пользователю ПОЛНУЮ информацию
    // об ОДНОЙ конкретной услуге (findById, updateService — "текущие данные",
    // deleteService — данные перед подтверждением удаления), в отличие
    // от printServices(...), который компактно показывает СПИСОК из
    // МНОЖЕСТВА услуг сразу.
    private void printService(GroomingService s) {
        System.out.println("ID: " + s.id());
        System.out.println("Название: " + s.title());
        System.out.println("Длительность: " + s.durationMinutes() + " мин.");
        System.out.println("Цена: " + s.price() + " руб.");
        System.out.println("Описание: " + s.description());
    }

    // Комментарий-описание метода.
    // Вспомогательный метод: обрезает строку до максимальной длины max,
    // добавляя многоточие "…" в конце, если строка была обрезана.

    // "private" — чисто техническая внутренняя деталь форматирования таблицы,
    // используется только внутри printServices(...).
    private String cut(String value, int max) {
        // Тернарный оператор: если строка УЖЕ не длиннее максимума —
        // возвращаем её без изменений; иначе — берём ПОДСТРОКУ от начала
        // до "max - 1" символа (оставляя место для одного символа многоточия)
        // и приклеиваем к ней символ "…", сигнализирующий пользователю,
        // что значение было обрезано и полный текст длиннее показанного.
        return value.length() <= max ? value : value.substring(0, max - 1) + "…";
    }
}