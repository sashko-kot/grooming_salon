// Пакет "ui" — этот класс завершает СЛОЙ ПОЛЬЗОВАТЕЛЬСКОГО ИНТЕРФЕЙСА
// и играет роль ТОЧКИ ВХОДА в консольную часть приложения: именно с него
// начинается взаимодействие с пользователем (обычно вызывается прямо
// из main-метода). В отличие от AdminMenuUI/ClientMenuUI/AnalyticsMenuUI/
// ExportMenuUI, которые реализуют КОНКРЕТНЫЕ сценарии работы с услугами,
// MainMenu не содержит никакой бизнес-логики сам по себе — его единственная
// задача СОБРАТЬ все остальные экраны (подменю) вместе и дать пользователю
// выбрать, В КАКОЙ из них перейти.
package ru.mirea.ui;

// Импортируем сервис — не для того, чтобы вызывать его методы напрямую
// (в этом классе НЕТ ни одного обращения вроде service.getAllServices()),
// а для того, чтобы ПЕРЕДАТЬ его дальше при создании каждого из подменю
// (см. конструктор ниже) — MainMenu выступает здесь как "точка сборки",
// которая один раз получает сервис и раздаёт его всем экранам, которым
// он нужен, вместо того чтобы каждое подменю создавало (или получало
// откуда-то ещё) свою собственную ссылку на сервис.
import ru.mirea.service.GroomingServiceService;

// Scanner — единый объект для чтения ввода пользователя, который
// создаётся ОДИН РАЗ здесь, в MainMenu, и затем передаётся тем же самым
// объектом во ВСЕ подменю (adminMenu.show(scanner), clientMenu.show(scanner)
// и так далее) — это гарантирует, что во всём приложении работает ровно
// один поток чтения System.in, независимо от того, в какое подменю
// переходит пользователь.
import java.util.Scanner;

// Комментарий-описание класса.
// Главное меню приложения.
// Здесь пользователь выбирает, в каком режиме он хочет работать:
// администратор, клиент, аналитика или экспорт.

// "public class" — класс должен быть виден извне пакета ui, так как,
// скорее всего, создаётся и запускается прямо из main-метода приложения
// (единственного места, где обычно и происходит первоначальная настройка:
// создание репозитория, сервиса и, наконец, главного меню).
public class MainMenu {

    // "private final" — поле сервиса устанавливается один раз в конструкторе
    // и больше не переприсваивается.
    //
    // Обратите внимание: это поле ХРАНИТСЯ в объекте MainMenu, но нигде
    // в теле класса (ни в конструкторе, ни в start()) НЕ ИСПОЛЬЗУЕТСЯ
    // напрямую — единственная его роль состоит в том, что оно было передано
    // в конструктор и тут же, ниже, отправлено дальше в конструкторы всех
    // четырёх подменю. Строго говоря, само по себе поле "service" в MainMenu
    // избыточно: конструктору достаточно было бы просто ПРИНЯТЬ параметр
    // "service" и передать его в adminMenu/clientMenu/analyticsMenu/exportMenu,
    // не сохраняя отдельную копию ссылки в собственном поле класса. Тем не
    // менее, хранение этой ссылки не является ошибкой — это, скорее,
    // небольшой избыточный "задел на будущее" (вдруг какому-то методу
    // MainMenu в дальнейшем потребуется сервис напрямую), который не влияет
    // на корректность работы программы.
    private final GroomingServiceService service;

    // Четыре поля ниже хранят уже ГОТОВЫЕ, СОЗДАННЫЕ объекты подменю —
    // ровно по одному экземпляру каждого класса на всё время жизни
    // MainMenu. Они создаются ОДИН РАЗ в конструкторе (см. ниже),
    // а не заново при каждом обращении пользователя к соответствующему
    // пункту меню — то есть, например, объект adminMenu будет одним
    // и тем же при первом заходе в раздел администратора и при повторном
    // заходе туда же после возврата в главное меню (переиспользование
    // объекта, а не создание нового при каждом входе в раздел).
    private final AdminMenuUI adminMenu;
    private final ClientMenuUI clientMenu;
    private final AnalyticsMenuUI analyticsMenu;
    private final ExportMenuUI exportMenu;

    // Комментарий-описание конструктора.
    // В конструкторе создаются все подменю приложения.

    // "public" — конструктор вызывается извне (как правило, из main-метода)
    // с уже готовым, настроенным объектом сервиса.
    public MainMenu(GroomingServiceService service) {
        // Сохраняем ссылку на сервис в собственном поле (см. пояснение выше
        // о том, что это поле дальше напрямую не используется).
        this.service = service;
        // Создаём по одному экземпляру КАЖДОГО подменю, передавая всем им
        // ОДИН И ТОТ ЖЕ объект service, полученный параметром конструктора —
        // это значит, что все подменю работают с ОДНИМИ и теми же данными
        // (через один и тот же сервис, а значит и один и тот же репозиторий
        // и одну и ту же базу данных "под капотом"), а не с какими-то
        // независимыми копиями. Именно поэтому, например, услугу, добавленную
        // через adminMenu, сразу же можно будет увидеть через clientMenu
        // или analyticsMenu — они смотрят "в одно и то же место".
        this.adminMenu = new AdminMenuUI(service);
        this.clientMenu = new ClientMenuUI(service);
        this.analyticsMenu = new AnalyticsMenuUI(service);
        this.exportMenu = new ExportMenuUI(service);
    }

    // Комментарий-описание метода.
    // Запускает бесконечный цикл меню программы.

    // "public" — метод, с которого фактически НАЧИНАЕТСЯ вся работа
    // консольного приложения; обычно вызывается один раз из main-метода
    // сразу после создания объекта MainMenu.
    // "void" — метод не возвращает значения: он работает до тех пор,
    // пока пользователь сам не выберет выход (пункт "0"), после чего просто
    // завершается.
    public void start() {
        // "try (Scanner scanner = new Scanner(System.in)) { ... }" —
        // это TRY-WITH-RESOURCES: специальная форма try, в скобках которой
        // объявляется и сразу инициализируется ресурс (здесь — Scanner),
        // который автоматически будет ЗАКРЫТ (вызван его метод close())
        // при выходе из блока try — неважно, завершится ли блок обычным
        // образом (через return) или из-за исключения. Scanner реализует
        // интерфейс AutoCloseable, поэтому его можно использовать именно
        // в такой конструкции.
        //
        // ВАЖНЫЙ НЮАНС, который стоит уметь объяснить: закрытие Scanner,
        // обёрнутого вокруг System.in, ЗАКРЫВАЕТ и сам System.in — то есть
        // стандартный поток ввода консоли. Так как start() вызывается один
        // раз за всё время жизни программы и сразу перед завершением этого
        // метода приложение обычно и так закончит работу, этот побочный
        // эффект здесь не создаёт проблем. Но если бы где-то в этом же
        // приложении ПОСЛЕ выхода из MainMenu.start() потребовалось ЕЩЁ РАЗ
        // прочитать что-то из System.in (например, создать новый
        // "new Scanner(System.in)" в другом месте), это привело бы к ошибке,
        // так как исходный поток ввода уже закрыт — это стоит держать
        // в уме как потенциальное архитектурное ограничение такого подхода.
        try (Scanner scanner = new Scanner(System.in)) {
            // "while (true)" — как и в show(...) остальных классов меню
            // этого пакета, бесконечный цикл: главное меню должно
            // показываться заново после того, как пользователь вернётся
            // из любого подменю (adminMenu.show(scanner) и т.д. — все они
            // сами возвращают управление обратно сюда, когда пользователь
            // выбирает "0. Назад" в СВОЁМ подменю). Единственный способ
            // выйти из ЭТОГО, самого внешнего цикла — явный return внутри
            // ветки case "0" ниже.
            while (true) {
                // Печатаем заголовок и рамку — чисто оформительский вывод,
                // отделяющий главное меню от предыдущего вывода на экране
                // (например, от результатов работы только что закрытого
                // подменю).
                System.out.println("\n========================================");
                System.out.println("        ГРУМИНГ-САЛОН");
                System.out.println("========================================");
                System.out.println("1. Администратор");
                System.out.println("2. Клиент");
                System.out.println("3. Аналитика");
                System.out.println("4. Экспорт данных");
                System.out.println("0. Выход");
                System.out.print("Выберите режим: ");

                // Стрелочный switch (Java 14+) без "break" — каждая ветка
                // вызывает show(scanner) СООТВЕТСТВУЮЩЕГО подменю, передавая
                // ему ТОТ ЖЕ САМЫЙ объект scanner, что был создан в try-with-
                // resources выше. Каждый вызов show(...) сам по себе является
                // БЛОКИРУЮЩИМ: пока пользователь работает внутри, скажем,
                // adminMenu (добавляет, ищет, удаляет услуги в цикле ЕГО
                // собственного show(...)), выполнение MainMenu.start()
                // "приостановлено" на этой самой строке ("case "1" ->
                // adminMenu.show(scanner);") и продолжится только тогда,
                // когда adminMenu.show(scanner) сам завершится (то есть
                // когда пользователь выберет "0. Назад" внутри админ-меню) —
                // после чего цикл while(true) в MainMenu заново напечатает
                // главное меню.
                switch (scanner.nextLine().trim()) {
                    case "1" -> adminMenu.show(scanner);
                    case "2" -> clientMenu.show(scanner);
                    case "3" -> analyticsMenu.show(scanner);
                    case "4" -> exportMenu.show(scanner);
                    // Ветка "0" отличается от остальных: она не просто
                    // выполняет одно выражение, а СНАЧАЛА печатает прощальное
                    // сообщение, и ТОЛЬКО ПОТОМ завершает метод через return —
                    // поэтому её тело взято в фигурные скобки {} (как и
                    // требует синтаксис стрелочного case, когда внутри
                    // не одно простое выражение, а последовательность
                    // операторов).
                    case "0" -> {
                        System.out.println("Работа программы завершена.");
                        // "return" здесь завершает весь метод start()
                        // целиком — а значит, и его цикл while(true).
                        // Сразу после этого return блок try-with-resources
                        // автоматически закроет scanner (см. пояснение выше),
                        // и метод start(), а вместе с ним, как правило,
                        // и вся программа, завершит работу.
                        return;
                    }
                    default -> System.out.println("Ошибка: неизвестная команда.");
                }
            }
        }
    }
}