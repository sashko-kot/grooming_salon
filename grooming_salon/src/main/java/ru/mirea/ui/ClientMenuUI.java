// Пакет "ui" — как и AdminMenuUI/AnalyticsMenuUI, этот класс относится
// к СЛОЮ ПОЛЬЗОВАТЕЛЬСКОГО ИНТЕРФЕЙСА, только предназначен для другой
// категории пользователей — КЛИЕНТОВ, а не администраторов. Поэтому набор
// операций здесь гораздо УЖЕ: клиент может только ПРОСМАТРИВАТЬ услуги
// (весь список или одну по ID), но не может их добавлять, изменять или
// удалять — этих пунктов в меню намеренно нет, а не просто "ещё не написаны".
// Разграничение "что видит клиент" и "что видит администратор" сделано
// НЕ через проверку прав внутри одного класса меню, а через СУЩЕСТВОВАНИЕ
// ДВУХ РАЗНЫХ классов UI (AdminMenuUI и ClientMenuUI), каждый из которых
// показывает только то подмножество действий, которое имеет смысл
// для соответствующей роли пользователя.
package ru.mirea.ui;

// Импортируем модель услуги — используется здесь только для чтения полей
// при печати (title(), price(), durationMinutes(), description(), id()).
import ru.mirea.model.GroomingService;

// Импортируем сервис — единственная точка входа для получения данных
// об услугах; клиентский UI, как и остальные классы этого пакета, не
// обращается к репозиторию или базе данных напрямую.
import ru.mirea.service.GroomingServiceService;

// Scanner — читает ввод пользователя из консоли; передаётся СНАРУЖИ
// в show(scanner), а не создаётся внутри класса — по той же причине,
// что и в AdminMenuUI/AnalyticsMenuUI: во всём приложении должен
// использоваться один и тот же поток чтения System.in.
import java.util.Scanner;

// "public class" — класс должен быть виден извне пакета, так как вызывается
// из общего меню приложения в момент, когда пользователь выбирает роль
// "клиент" (в отличие от роли "администратор", которая ведёт в AdminMenuUI).
public class ClientMenuUI {

    // "private final" — ссылка на сервис устанавливается один раз через
    // конструктор и больше не меняется за время жизни объекта; это
    // ЕДИНСТВЕННОЕ поле класса — в отличие от AdminMenuUI и AnalyticsMenuUI,
    // здесь нет собственного поля GroomingAnalytics, поскольку клиентское
    // меню не показывает никакой аналитики (среднюю цену, группировку
    // и т.п.) — эти возможности предназначены только для администратора.
    private final GroomingServiceService service;

    // Комментарий-описание конструктора.
    // Создаёт клиентское меню, получая сервис снаружи через внедрение
    // зависимости — сам класс не создаёт сервис самостоятельно и не знает,
    // как именно он был настроен (какой репозиторий или база данных
    // используются внутри).
    public ClientMenuUI(GroomingServiceService service) {
        // "this.service" — обращение к полю класса, чтобы отличить его
        // от одноимённого параметра конструктора.
        this.service = service;
    }

    // Комментарий-описание метода.
    // Показывает меню клиента и обрабатывает выбор пользователя в цикле —
    // структура метода полностью аналогична show(...) в AdminMenuUI
    // и AnalyticsMenuUI (см. подробные пояснения там же), только здесь
    // пунктов всего два вместо восьми/пяти — просмотр списка услуг
    // и поиск конкретной услуги по ID.
    public void show(Scanner scanner) {
        // "while (true)" — бесконечный цикл: меню показывается заново
        // после каждого действия, единственный выход — return в ветке "0".
        while (true) {
            System.out.println("\n=== МЕНЮ КЛИЕНТА ===");
            System.out.println("1. Посмотреть доступные услуги");
            System.out.println("2. Найти услугу по ID");
            System.out.println("0. Назад");
            System.out.print("Выберите действие: ");
            // Стрелочный switch (Java 14+) без "break" — каждая ветка
            // вызывает соответствующий приватный метод-обработчик.
            switch (scanner.nextLine().trim()) {
                case "1" -> printServices();
                case "2" -> findService(scanner);
                case "0" -> {
                    return;
                }
                default -> System.out.println("Ошибка: неверный пункт меню.");
            }
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "1": получает у сервиса полный список услуг
    // и печатает его компактной таблицей — по смыслу это то же самое,
    // что printAll()/printServices(...) в AdminMenuUI, но реализовано
    // здесь как ОДИН метод без отдельного переиспользуемого помощника
    // печати таблицы, так как в клиентском меню таблица печатается
    // только в этом единственном месте (в отличие от AdminMenuUI,
    // где printServices(...) вызывался из нескольких пунктов меню
    // и поэтому имело смысл вынести его в отдельный метод).
    private void printServices() {
        // Оборачиваем работу с сервисом в try/catch — service.getAllServices()
        // теоретически может выбросить RuntimeException (например, при сбое
        // обращения к базе данных внутри репозитория), и клиентский UI не
        // должен "падать" из-за этого, а должен показать понятное сообщение
        // об ошибке и вернуть управление обратно в меню (цикл в show(...)
        // покажет меню заново).
        try {
            // "var" — вывод типа компилятором (type inference, начиная
            // с Java 10): компилятор сам определяет, что тип переменной
            // services — это List<GroomingService>, глядя на то, что
            // возвращает service.getAllServices(). Использование "var"
            // здесь не меняет поведение программы (переменная всё равно
            // остаётся строго типизированной на этапе компиляции), а лишь
            // сокращает запись — в отличие от AdminMenuUI, где аналогичная
            // переменная была объявлена явным типом
            // "List<GroomingService> services = ...".
            var services = service.getAllServices();
            // Если услуг нет вообще, печатаем понятное сообщение вместо
            // пустой таблицы из одних заголовков без единой строки данных.
            if (services.isEmpty()) {
                System.out.println("Доступных услуг нет.");
                return;
            }
            // "System.out.printf(...)" с "%-Ns" — печать с выравниванием
            // ПО ЛЕВОМУ краю в поле шириной N символов (минус перед числом
            // означает выравнивание влево, без минуса было бы выравнивание
            // вправо) — тот же приём форматирования таблицы, что и
            // в AdminMenuUI.printServices(...). Обратите внимание: здесь
            // колонок ЧЕТЫРЕ (ID, Название, Мин, Цена), а не пять, как
            // в административной таблице — колонка "Описание" клиенту
            // в общем списке не показывается (её можно увидеть только
            // при просмотре ОДНОЙ конкретной услуги через findService(...)
            // ниже) — это осознанное решение сделать общий список компактнее.
            System.out.printf("%-4s | %-35s | %-12s | %-10s%n", "ID", "Название", "Мин", "Цена");
            // "-".repeat(72) — разделительная линия под заголовком таблицы;
            // число 72 подобрано под суммарную ширину ЧЕТЫРЁХ колонок этой
            // таблицы (в AdminMenuUI, где колонок пять и они шире, использовалось
            // число 110) — так линия визуально совпадает по длине со строками
            // данных.
            System.out.println("-".repeat(72));
            // Обычный "for-each" цикл — для каждой услуги печатаем одну строку
            // теми же спецификаторами форматирования, что и в заголовке.
            // В отличие от AdminMenuUI, здесь названия и описания НЕ обрезаются
            // через вспомогательный метод cut(...) — по всей видимости, это
            // упрощение для клиентского экрана (либо предполагается, что
            // длинные названия здесь маловероятны, либо просто не было
            // необходимости добавлять эту защиту от "расползания" таблицы).
            for (GroomingService s : services) {
                System.out.printf("%-4d | %-35s | %-12d | %-10s%n",
                        s.id(), s.title(), s.durationMinutes(), s.price());
            }
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "2": запрашивает у пользователя ID и печатает
    // подробную карточку одной услуги, если она найдена.
    private void findService(Scanner scanner) {
        // "InputHelper.readLong(scanner, prompt, 1)" — читает целое число
        // типа long с минимальным допустимым значением 1 (id не может быть
        // меньше 1); вызывается ДО try/catch, так как сам процесс чтения
        // и проверки формата числа не связан с исключениями, которые может
        // бросить сервис — это техническая деталь ввода, а не обращение
        // к бизнес-логике.
        long id = InputHelper.readLong(scanner, "ID услуги: ", 1);
        try {
            // "service.getServiceById(id).ifPresentOrElse(consumer, runnable)" —
            // вызов метода сервиса и сразу же, "цепочкой", обработка результата
            // через Optional.ifPresentOrElse: если услуга найдена, выполняется
            // ПЕРВАЯ лямбда (получает найденную услугу как параметр "s"),
            // если не найдена — ВТОРАЯ (без параметров). Тот же приём,
            // что и в AdminMenuUI.findById(...), только там вместо лямбды
            // для "найдено" использовалась ссылка на метод (this::printService),
            // а здесь — лямбда с телом ПРЯМО НА МЕСТЕ, так как отдельного
            // переиспользуемого метода печати карточки услуги в этом классе
            // нет (в клиентском меню карточка услуги печатается только
            // в этом единственном месте, поэтому выносить её в отдельный
            // метод printService(...), как в AdminMenuUI, не было
            // необходимости).
            service.getServiceById(id).ifPresentOrElse(
                    s -> {
                        // "\n" перед названием — добавляет пустую строку перед
                        // карточкой услуги для визуального отделения от вопроса
                        // "ID услуги: ", напечатанного строкой раньше.
                        System.out.println("\n" + s.title());
                        System.out.println("Длительность: " + s.durationMinutes() + " мин.");
                        System.out.println("Цена: " + s.price() + " руб.");
                        // В отличие от общего списка в printServices() выше,
                        // здесь описание услуги ПОКАЗЫВАЕТСЯ — то есть подробная
                        // карточка одной услуги содержит больше информации,
                        // чем строка в общей таблице, что вполне логично:
                        // клиент, заинтересовавшийся конкретной услугой,
                        // должен увидеть её полное описание.
                        System.out.println("Описание: " + s.description());
                    },
                    () -> System.out.println("Услуга не найдена."));
        } catch (RuntimeException e) {
            System.out.println("Ошибка: " + e.getMessage());
        }
    }
}