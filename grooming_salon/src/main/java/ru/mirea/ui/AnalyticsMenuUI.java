// Пакет "ui" — этот класс, как и AdminMenuUI, относится к СЛОЮ ПОЛЬЗОВАТЕЛЬСКОГО
// ИНТЕРФЕЙСА: он печатает меню, читает выбор и ввод пользователя через консоль
// и выводит результаты аналитики на экран. Сам класс не считает ничего
// "руками" — вся математика (среднее, медиана, группировка и т.д.) находится
// в GroomingAnalytics, а весь доступ к данным об услугах — в
// GroomingServiceService; этот класс лишь СВЯЗЫВАЕТ их с консольным вводом-выводом.
package ru.mirea.ui;

// Импортируем аналитику — именно она выполняет все вычисления над списком
// услуг (среднее, медиана, самая долгая услуга, фильтрация по цене,
// группировка по длительности).
import ru.mirea.analytics.GroomingAnalytics;

// Импортируем модель услуги — нужна здесь только для того, чтобы читать
// поля (title(), price(), durationMinutes() и т.д.) при печати результатов.
import ru.mirea.model.GroomingService;

// Импортируем сервис — единственный способ получить список услуг
// (services.getAllServices()); класс аналитики сам по себе не знает,
// как получить данные, — их ему всегда передают снаружи.
import ru.mirea.service.GroomingServiceService;

// BigDecimal — тип суммы, которую вводит пользователь в пункте
// "Услуги не дороже заданной цены" (метод cheaperThan).
import java.math.BigDecimal;

// List — тип, в котором сервис и аналитика возвращают списки услуг.
import java.util.List;

// Map — тип результата группировки услуг по длительности в методе grouping().
import java.util.Map;

// Scanner — читает текст, введённый пользователем в консоли; как и в
// AdminMenuUI, передаётся СНАРУЖИ в show(scanner), а не создаётся внутри
// класса, чтобы во всём приложении использовался один и тот же поток
// чтения ввода System.in.
import java.util.Scanner;

// "public class" — как и AdminMenuUI, этот класс должен быть виден извне
// пакета (вызывается из общего меню приложения) и представляет собой
// объект СО СВОИМ ПОВЕДЕНИЕМ (методы печати меню и обработки выбора),
// а не просто контейнер данных.
public class AnalyticsMenuUI {

    // "private final" — ссылка на сервис устанавливается один раз через
    // конструктор и больше не меняется; весь доступ к данным об услугах
    // идёт только через неё.
    private final GroomingServiceService service;

    // Обратите внимание на РАЗНИЦУ с AdminMenuUI: там поле analytics
    // сначала объявлялось без инициализации, а присваивалось внутри тела
    // конструктора ("this.analytics = new GroomingAnalytics();"). Здесь же
    // используется инициализация ПРЯМО НА МЕСТЕ объявления поля —
    // "= new GroomingAnalytics()" сразу после типа. Оба способа корректны
    // и приводят к одинаковому результату: поле будет проинициализировано
    // до того, как выполнится тело конструктора. Инициализация на месте
    // особенно уместна именно здесь, потому что GroomingAnalytics не зависит
    // ни от каких параметров конструктора AnalyticsMenuUI — создавать его
    // всегда одинаково, независимо от того, какой service передали снаружи,
    // поэтому нет смысла явно писать это в теле конструктора.
    private final GroomingAnalytics analytics = new GroomingAnalytics();

    // Комментарий-описание конструктора.
    // Создаёт экран аналитики, получая сервис снаружи через внедрение
    // зависимости (dependency injection) — сам класс не знает и не должен
    // знать, откуда взялся сервис и как он настроен.
    public AnalyticsMenuUI(GroomingServiceService service) {
        // "this.service" — обращение к полю класса, чтобы отличить его
        // от одноимённого параметра конструктора.
        this.service = service;
    }

    // Комментарий-описание метода.
    // Показывает меню аналитики и обрабатывает выбор пользователя в цикле,
    // пока пользователь не выберет "0" (назад) — структура метода полностью
    // аналогична show(...) в AdminMenuUI, см. подробные пояснения там же.
    public void show(Scanner scanner) {
        // "while (true)" — бесконечный цикл: меню должно появляться заново
        // после каждого действия, а единственный выход — return в ветке "0".
        while (true) {
            System.out.println("\n=== АНАЛИТИКА ===");
            System.out.println("1. Средняя стоимость");
            System.out.println("2. Медианная стоимость");
            System.out.println("3. Самая длинная процедура");
            System.out.println("4. Услуги не дороже заданной цены");
            System.out.println("5. Группировка: быстрые / комплексные");
            System.out.println("0. Назад");
            System.out.print("Выберите действие: ");

            // Стрелочный switch (Java 14+) без "break" — каждая ветка вызывает
            // соответствующий приватный метод-обработчик. Обратите внимание:
            // только пункт "4" (cheaperThan) принимает scanner параметром —
            // остальным методам (average, median, longest, grouping)
            // дополнительный пользовательский ввод не требуется, они сразу
            // печатают готовый результат по всем услугам без уточняющих
            // вопросов.
            switch (scanner.nextLine().trim()) {
                case "1" -> average();
                case "2" -> median();
                case "3" -> longest();
                case "4" -> cheaperThan(scanner);
                case "5" -> grouping();
                case "0" -> {
                    return;
                }
                default -> System.out.println("Ошибка: неверный пункт меню.");
            }
        }
    }

    // Комментарий-описание метода.
    // Внутренний вспомогательный метод: безопасно получает полный список услуг
    // у сервиса, "гасит" возможное исключение и возвращает пустой список
    // вместо того, чтобы позволить исключению прервать выполнение метода.

    // "private" — метод используется только внутри этого класса, вызывается
    // из average(), median(), longest(), cheaperThan(), grouping() — то есть
    // практически из КАЖДОГО обработчика пункта меню, которому нужны данные
    // об услугах. Вынесение обращения к сервису в один общий метод избавляет
    // от повторения одинакового try/catch в каждом из этих пяти мест
    // (что как раз и было сделано в AdminMenuUI — там try/catch писался
    // отдельно в каждом методе; здесь автор выбрал более компактный подход,
    // сосредоточив обработку ошибок в одном месте).
    private List<GroomingService> services() {
        try {
            return service.getAllServices();
        } catch (RuntimeException e) {
            // Если сервис бросил исключение (например, при проблеме с базой
            // данных внутри репозитория), печатаем пользователю понятное
            // сообщение прямо здесь...
            System.out.println("Ошибка при получении данных: " + e.getMessage());
            // ...а вызывающему методу (average, median и т.д.) возвращаем
            // ПУСТОЙ список, а не null и не перевыброшенное исключение.
            // Благодаря этому каждый из методов-обработчиков может спокойно
            // работать с результатом (передавать его в analytics.*), не думая
            // отдельно о null-проверках и не оборачивая КАЖДЫЙ вызов
            // analytics.* в собственный try/catch — вся забота об ошибках
            // сосредоточена именно здесь. "List.of()" — создаёт НЕИЗМЕНЯЕМЫЙ
            // пустой список (в отличие от, скажем, "new ArrayList<>()"),
            // что вполне уместно, так как этот пустой список никто и не должен
            // пытаться менять — он используется только для чтения дальше
            // по коду.
            return List.of();
        }
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "1": печатает среднюю цену по всем услугам.

    // Обратите внимание, что здесь, в отличие от showAnalytics() в
    // AdminMenuUI, НЕТ отдельной проверки на пустой список услуг перед
    // вызовом analytics.calculateAveragePrice(...) — по всей видимости,
    // сама GroomingAnalytics умеет корректно обработать пустой список
    // (например, вернуть ноль вместо деления на ноль), и поэтому вызывающему
    // коду в UI не нужно дублировать эту проверку самостоятельно.
    private void average() {
        // "services()" — вызываем приватный метод-обёртку выше, а не
        // "service.getAllServices()" напрямую, чтобы автоматически получить
        // защиту от исключений и пустой список в случае ошибки.
        System.out.println("Средняя стоимость: " + analytics.calculateAveragePrice(services()) + " руб.");
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "2": печатает медианную цену по всем услугам.
    // Медиана — значение, которое оказывается ровно посередине упорядоченного
    // по возрастанию списка цен (в отличие от среднего арифметического,
    // медиана менее чувствительна к отдельным очень дорогим или очень дешёвым
    // "выбросам" в данных).
    private void median() {
        System.out.println("Медианная стоимость: " + analytics.calculateMedianPrice(services()) + " руб.");
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "3": находит и печатает услугу с наибольшей
    // длительностью.
    private void longest() {
        GroomingService result = analytics.getLongestService(services());
        // Явная проверка на null здесь ОБЯЗАТЕЛЬНА (в отличие от average()
        // и median() выше): если список услуг пуст, аналитике попросту нечего
        // возвращать в качестве "самой долгой услуги", и разумный способ
        // сигнализировать об этом — вернуть null, а не бросать исключение
        // (для сравнения — так же было устроено и в AdminMenuUI.showAnalytics()).
        // Без этой проверки следующая строка (result.title()) привела бы
        // к NullPointerException при пустом списке услуг.
        if (result == null) {
            System.out.println("Нет данных для анализа.");
            // Явный return — прерываем метод, дальше по коду печатать нечего.
            return;
        }
        // "%s" — подставляет строку (название услуги), "%d" — подставляет
        // целое число (длительность в минутах), "%n" — переносит строку
        // платформонезависимым способом (как и в printServices у AdminMenuUI).
        System.out.printf("Самая длинная процедура: %s — %d мин.%n", result.title(), result.durationMinutes());
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "4": запрашивает у пользователя максимальную
    // цену и печатает список услуг, которые ей не дороже.
    private void cheaperThan(Scanner scanner) {
        // "InputHelper.readMoney(...)" — вспомогательный метод (как и в
        // AdminMenuUI), который сам читает и проверяет корректность введённой
        // денежной суммы, избавляя этот класс от ручных проверок формата ввода.
        BigDecimal maxPrice = InputHelper.readMoney(scanner, "Максимальная цена: ");
        List<GroomingService> result = analytics.findServicesCheaperThan(services(), maxPrice);
        if (result.isEmpty()) {
            System.out.println("Подходящих услуг не найдено.");
            return;
        }
        // "result.forEach(s -> ...)" — для каждой подходящей услуги печатаем
        // одну строку с её id, названием и ценой. Используется лямбда-выражение
        // вместо обычного цикла for — более компактная запись для простого
        // "напечатать что-то для каждого элемента списка" без необходимости
        // явно заводить переменную-счётчик или временную переменную цикла.
        result.forEach(s -> System.out.printf("%d. %s — %s руб.%n", s.id(), s.title(), s.price()));
    }

    // Комментарий-описание метода.
    // Обрабатывает пункт меню "5": группирует все услуги по длительности
    // (например, на "быстрые" и "комплексные" — конкретные названия категорий
    // определяются внутри GroomingAnalytics.groupByDuration) и печатает
    // каждую группу отдельным блоком.
    private void grouping() {
        // Получаем Map, где ключ — название категории (строка), а значение —
        // список услуг, попавших в эту категорию.
        Map<String, List<GroomingService>> groups = analytics.groupByDuration(services());
        // "groups.forEach((name, list) -> { ... })" — перебираем ВСЕ пары
        // ключ-значение в Map: для каждой категории (name) со своим списком
        // услуг (list) выполняем переданный блок кода — аналогично тому,
        // как это устроено в AdminMenuUI.showAnalytics(), только там
        // группировка была лишь ЧАСТЬЮ большого метода, а здесь это отдельный,
        // самостоятельный пункт меню.
        groups.forEach((name, list) -> {
            // "\n" перед названием группы — добавляет пустую строку ПЕРЕД
            // каждой новой категорией, чтобы визуально отделить группы друг
            // от друга в консольном выводе.
            System.out.println("\n" + name + ":");
            // Для каждой услуги внутри текущей группы печатаем строку
            // с отступом-дефисом ("- "), её названием и длительностью —
            // такой же приём визуального выделения "элемента списка внутри
            // группы", как и в AdminMenuUI.showAnalytics().
            list.forEach(s -> System.out.printf("- %s (%d мин.)%n", s.title(), s.durationMinutes()));
        });
    }
}