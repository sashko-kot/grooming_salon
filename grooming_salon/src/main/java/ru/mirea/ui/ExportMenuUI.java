// Пакет "ui" — этот класс, как и остальные классы этого пакета
// (AdminMenuUI, AnalyticsMenuUI, ClientMenuUI), относится к СЛОЮ
// ПОЛЬЗОВАТЕЛЬСКОГО ИНТЕРФЕЙСА: он читает ввод пользователя (имя файла)
// и координирует вызов экспорта, но сам НЕ занимается ни получением данных
// напрямую из базы (это делает сервис), ни форматированием CSV и записью
// на диск (это отдельная зона ответственности класса GroomingExporter).
package ru.mirea.ui;

// Импортируем класс-экспортёр — судя по названию (GroomingExporter)
// и вызову exportToCsv(...), это отдельный класс (скорее всего со статическими
// методами, раз вызывается как "GroomingExporter.exportToCsv(...)", а не
// через созданный объект), который умеет превращать список услуг в CSV-файл.
// Логика самого форматирования CSV (разделители, экранирование, кодировка
// файла и т.д.) полностью находится ВНУТРИ этого класса и не касается UI —
// UI лишь передаёт туда ЧТО экспортировать (список услуг) и КУДА (путь к файлу).
import ru.mirea.exporter.GroomingExporter;

// Импортируем сервис — единственный способ получить список услуг для
// экспорта; UI, как и остальные классы этого пакета, не обращается
// к репозиторию или базе данных напрямую.
import ru.mirea.service.GroomingServiceService;

// Path — современный (начиная с Java 7, пакет java.nio.file) способ работать
// с путями к файлам в файловой системе, предпочтительный по сравнению
// со старым классом java.io.File — используется здесь для представления
// пути к создаваемому CSV-файлу.
import java.nio.file.Path;

// Scanner — читает ввод пользователя из консоли; как и в остальных классах
// пакета ui, передаётся СНАРУЖИ в show(scanner), а не создаётся внутри,
// чтобы использовать единый поток чтения System.in во всём приложении.
import java.util.Scanner;

// "public class" — класс должен быть виден извне пакета, так как вызывается
// из общего меню приложения, когда пользователь выбирает пункт "экспорт
// данных" (независимо от того, администратор это или клиент — судя по
// отсутствию каких-либо проверок роли внутри этого класса, экспорт, видимо,
// доступен из общего меню, а не спрятан внутри AdminMenuUI).
public class ExportMenuUI {

    // "private final" — ссылка на сервис устанавливается один раз через
    // конструктор; это ЕДИНСТВЕННОЕ поле класса — экспортёр (GroomingExporter)
    // не хранится как поле объекта, а вызывается напрямую как СТАТИЧЕСКИЙ
    // метод (см. show(...) ниже: "GroomingExporter.exportToCsv(...)"),
    // поэтому отдельного поля для него не требуется — в отличие, например,
    // от GroomingAnalytics в AnalyticsMenuUI/AdminMenuUI, который хранился
    // как поле именно потому, что вызывался через созданный объект,
    // а не статически.
    private final GroomingServiceService service;

    // Комментарий-описание конструктора.
    // Создаёт экран экспорта, получая сервис снаружи через внедрение
    // зависимости — сам класс не создаёт сервис самостоятельно.
    public ExportMenuUI(GroomingServiceService service) {
        // "this.service" — обращение к полю класса, чтобы отличить его
        // от одноимённого параметра конструктора.
        this.service = service;
    }

    // Комментарий-описание метода.
    // Показывает экран экспорта, спрашивает у пользователя имя файла
    // и выполняет экспорт всех услуг в CSV.

    // Обратите внимание на СТРУКТУРНОЕ ОТЛИЧИЕ этого метода show(...) от
    // show(...) в AdminMenuUI/AnalyticsMenuUI/ClientMenuUI: там show(...)
    // был БЕСКОНЕЧНЫМ ЦИКЛОМ с меню из нескольких пунктов и переключателем
    // switch, возвращающимся в начало после каждого действия. Здесь же
    // никакого цикла и switch нет — экспорт представляет собой ОДНО простое
    // линейное действие (спросить имя файла -> выполнить экспорт -> сообщить
    // результат), поэтому после однократного выполнения метод сразу
    // завершается сам по себе (обычным образом, дойдя до конца тела метода),
    // а не через явный return из цикла, как в остальных классах меню.
    public void show(Scanner scanner) {
        System.out.println("\n=== ЭКСПОРТ ===");

        // Просим пользователя ввести имя файла, с подсказкой в квадратных
        // скобках, какое имя будет использовано "по умолчанию", если
        // пользователь ничего не введёт.
        //
        // ВАЖНЫЙ НЮАНС, который стоит уметь объяснить: здесь вызывается
        // именно "InputHelper.readRequiredString(...)" — судя по названию
        // (и по использованию этого же метода в AdminMenuUI/AnalyticsMenuUI
        // для полей вроде названия услуги), этот метод, скорее всего,
        // ГАРАНТИРУЕТ, что вернёт непустую строку (то есть сам не даст ввести
        // пустое значение, вероятно, попросив пользователя ввести заново).
        // Но чуть ниже в этом же методе стоит проверка
        // "if (fileName.isBlank()) fileName = "...";", как будто пустая
        // строка ВСЁ ЖЕ возможна как результат readRequiredString(...).
        // Это выглядит как ЛОГИЧЕСКАЯ НЕСОСТЫКОВКА между именем метода
        // ("readRequiredString" — "прочитать ОБЯЗАТЕЛЬНУЮ строку") и тем,
        // как он используется здесь (с расчётом на то, что пустой ввод
        // всё же может произойти и означать "взять имя файла по умолчанию").
        // Возможно, было бы правильнее использовать другой метод чтения
        // (например, "readOptionalString" или обычный "scanner.nextLine()"),
        // раз пустой ввод здесь — ожидаемый и допустимый сценарий, а не
        // ошибка пользователя. Тем не менее, из-за того как устроена
        // проверка "isBlank()" ниже, код будет работать корректно даже
        // если readRequiredString каким-то образом всё-таки вернёт пустую
        // строку — просто само сочетание имени метода и способа его
        // использования здесь стоит иметь в виду как не самый чистый
        // архитектурный момент.
        String fileName = InputHelper.readRequiredString(scanner, "Имя CSV-файла [grooming_services.csv]: ");

        // Если пользователь не ввёл имя файла (строка оказалась пустой
        // или состоящей только из пробелов) — подставляем имя файла
        // по умолчанию.
        //
        // Обратите внимание: это ОДНОСТРОЧНЫЙ "if" БЕЗ фигурных скобок {} —
        // в Java это допустимо, когда телом условия является РОВНО ОДИН
        // оператор ("fileName = ..."). Такой стиль компактнее, но менее
        // безопасен при дальнейшем редактировании кода: если бы кто-то
        // позже добавил вторую строку под этот if, не поставив фигурные
        // скобки, вторая строка выполнялась бы ВСЕГДА, а не только при
        // истинности условия — это частая причина трудноуловимых ошибок,
        // поэтому многие руководства по стилю Java рекомендуют всегда
        // использовать {} даже для однострочных условий.
        if (fileName.isBlank())
            fileName = "grooming_services.csv";

        // Если пользователь ввёл имя без расширения ".csv" (например, просто
        // "услуги" или "услуги.CSV" с другим регистром букв), добавляем
        // расширение автоматически, чтобы итоговый файл гарантированно
        // имел правильное расширение.
        //
        // "fileName.toLowerCase().endsWith(".csv")" — проверка выполняется
        // на строке, ПРИВЕДЁННОЙ К НИЖНЕМУ РЕГИСТРУ, а не на исходной
        // "fileName" — это сделано специально, чтобы проверка была
        // НЕЧУВСТВИТЕЛЬНА к регистру букв: имя файла "услуги.CSV" (с большими
        // буквами в расширении) должно считаться уже имеющим расширение
        // ".csv" и не должно превратиться в "услуги.CSV.csv". При этом
        // сама переменная fileName при добавлении расширения (`fileName += ".csv"`)
        // остаётся с оригинальным регистром букв пользователя — изменяется
        // только временная строка для целей ПРОВЕРКИ, а не сама переменная.
        if (!fileName.toLowerCase().endsWith(".csv"))
            fileName += ".csv";

        try {
            // "Path.of(fileName)" — создаёт объект Path (представление пути
            // в файловой системе) из введённой пользователем строки. Так как
            // путь не абсолютный (пользователь вводит просто "имя.csv",
            // а не полный путь вроде "/home/user/имя.csv"), итоговый файл
            // будет создан ОТНОСИТЕЛЬНО текущей рабочей директории, из которой
            // была запущена программа — отсюда и важность следующей строки,
            // печатающей АБСОЛЮТНЫЙ путь, чтобы пользователь точно понимал,
            // куда именно был сохранён файл.
            Path target = Path.of(fileName);
            // Передаём экспортёру ДВЕ вещи: свежий список всех услуг,
            // полученный через сервис (service.getAllServices()), и целевой
            // путь для сохранения — сам GroomingExporter отвечает за то,
            // как именно превратить список объектов GroomingService в текст
            // CSV-формата (разделители, заголовки колонок, экранирование
            // спецсимволов и т.д.) и записать этот текст в файл по указанному
            // пути.
            GroomingExporter.exportToCsv(service.getAllServices(), target);
            // "target.toAbsolutePath()" — превращает (возможно, относительный)
            // путь в АБСОЛЮТНЫЙ, разворачивая его относительно текущей рабочей
            // директории — так пользователь видит полный, однозначный путь
            // к созданному файлу, а не просто то короткое имя, которое сам ввёл.
            System.out.println("Экспорт выполнен: " + target.toAbsolutePath());
        } catch (Exception e) {
            // "catch (Exception e)", а НЕ более узкий "catch (RuntimeException e)",
            // как в остальных классах пакета ui (AdminMenuUI, AnalyticsMenuUI,
            // ClientMenuUI) — это осознанное расширение перехватываемых типов
            // исключений. Причина: запись файла на диск — операция ввода-вывода,
            // которая может завершиться CHECKED-исключением java.io.IOException
            // (например, если у пользователя нет прав на запись в текущую
            // директорию, или диск переполнен) — а IOException НЕ является
            // подклассом RuntimeException, поэтому его нужно либо объявлять
            // в сигнатуре метода через "throws", либо перехватывать явно.
            // Ловя базовый класс "Exception" (родитель и для checked-,
            // и для unchecked-исключений), этот catch гарантированно
            // "поймает" и IOException при записи файла, и любые
            // RuntimeException, которые мог бы бросить сервис при получении
            // списка услуг — всё это в одном месте, без необходимости писать
            // два отдельных catch-блока.
            System.out.println("Ошибка экспорта: " + e.getMessage());
        }
    }
}