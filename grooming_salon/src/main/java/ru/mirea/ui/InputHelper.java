// Пакет "ui" — хотя этот класс формально лежит в том же пакете, что
// и AdminMenuUI/AnalyticsMenuUI/ClientMenuUI/ExportMenuUI, по СМЫСЛУ он
// занимает несколько особое место: это не "экран меню" сам по себе,
// а ОБЩАЯ ТЕХНИЧЕСКАЯ УТИЛИТА для чтения и проверки пользовательского
// ввода, которой пользуются ВСЕ остальные классы пакета ui. Именно
// благодаря вынесению этой логики сюда каждому из классов AdminMenuUI,
// AnalyticsMenuUI, ClientMenuUI и ExportMenuUI не приходится заново
// писать циклы "спрашивать, пока не введут корректное значение" —
// они просто вызывают готовые статические методы этого класса.
package ru.mirea.ui;

// BigDecimal — тип для точных денежных вычислений, возвращается методом
// readMoney(...) ниже; выбор именно BigDecimal (а не double/float) важен,
// так как обычные числа с плавающей точкой могут давать неточности при
// денежных расчётах (например, 0.1 + 0.2 не всегда равно ровно 0.3
// в double), а BigDecimal хранит число точно, без такой погрешности.
import java.math.BigDecimal;

// Scanner — сам класс InputHelper НЕ создаёт объект Scanner самостоятельно
// (в отличие, например, от создания нового Scanner(System.in) где-то
// в точке входа программы) — каждый статический метод здесь ПРИНИМАЕТ
// готовый Scanner параметром, чтобы во всём приложении читался один
// и тот же поток ввода System.in, а не несколько независимых Scanner
// поверх одного и того же источника (что могло бы привести к путанице
// при чтении).
import java.util.Scanner;

// Комментарий-описание класса.
// Утилитный класс для ввода данных с консоли.
// Он помогает безопасно считывать строки, числа, цену и ответы да/нет.

// "public" — класс должен быть виден и использоваться из всех классов
// пакета ui (и, возможно, за его пределами), которым нужно читать ввод
// пользователя.
//
// "final" — класс НЕ предназначен для наследования: у него нет ни одного
// метода экземпляра (все методы статические, см. ниже), поэтому создавать
// подклассы, переопределяющие какое-либо поведение, попросту нет смысла —
// "final" явно запрещает такое наследование, защищая класс от случайного
// расширения там, где это архитектурно не задумано. Такой стиль (final-класс
// с приватным конструктором и только статическими методами) — стандартный
// и широко распространённый паттерн для "утилитных классов" в Java
// (похожий пример из стандартной библиотеки — класс java.util.Collections).
public final class InputHelper {

    // Комментарий-описание конструктора.
    // "private" — конструктор без параметров сделан приватным СОЗНАТЕЛЬНО,
    // чтобы НИКТО (ни другой код в этом же пакете, ни тем более код снаружи)
    // не мог создать объект "new InputHelper()". Это логично: у класса нет
    // ни одного поля экземпляра и ни одного метода экземпляра — создавать
    // объект этого класса попросту незачем, все его возможности доступны
    // через статические методы напрямую по имени класса
    // (например, "InputHelper.readRequiredString(...)"), без создания
    // объекта-посредника. Пустое тело конструктора здесь только для того,
    // чтобы явно "перекрыть" автоматически создаваемый Java конструктор
    // по умолчанию (который без этой строчки был бы публичным).
    private InputHelper() {
    }

    // Комментарий-описание метода.
    // Считывает непустую строку.

    // "public static" — метод вызывается напрямую по имени класса,
    // без создания объекта InputHelper (что и не получилось бы, так как
    // конструктор приватный, как отмечено выше). Именно этот метод
    // используется, например, в AdminMenuUI.addService(...) для чтения
    // названия и описания услуги, или в ExportMenuUI.show(...) для чтения
    // имени файла.
    public static String readRequiredString(Scanner scanner, String prompt) {
        // "while (true)" — метод НЕ возвращает управление вызывающему коду,
        // пока не получит от пользователя действительно корректное значение —
        // единственный способ выйти из этого цикла — оператор "return" внутри
        // самого цикла, при успешном вводе. Такой приём (бесконечный цикл
        // "спрашивать, пока не введут правильно" + return при успехе)
        // повторяется здесь и во всех остальных методах этого класса ниже —
        // это единообразный, легко узнаваемый паттерн для методов чтения
        // ввода с проверкой.
        while (true) {
            // "print", а не "println" — приглашение к вводу должно остаться
            // на той же строке, где пользователь начнёт печатать ответ.
            System.out.print(prompt);
            // "scanner.nextLine().trim()" — читаем всю строку целиком (а не
            // отдельное слово через scanner.next()) и сразу убираем случайные
            // пробелы по краям (например, если пользователь случайно нажал
            // пробел до или после текста).
            String value = scanner.nextLine().trim();
            // "!value.isEmpty()" — проверяем, что после удаления пробелов
            // по краям строка НЕ оказалась пустой. Обратите внимание: здесь
            // используется именно "isEmpty()" (строка нулевой длины ""),
            // а не "isBlank()" (который считал бы пустыми и строки из одних
            // пробелов) — но благодаря предварительному ".trim()" СТРОКОЙ ВЫШЕ
            // это не имеет значения: строка из одних пробелов после trim()
            // всё равно превратится в "" и будет поймана проверкой isEmpty(),
            // так что на практике оба варианта работали бы здесь одинаково —
            // просто выбран один конкретный способ проверки из двух
            // равнозначных для данного случая (сравните с сервисным слоем
            // GroomingServiceService, где для поля title используется именно
            // isBlank() напрямую, БЕЗ предварительного trim() перед проверкой).
            if (!value.isEmpty()) {
                // Если значение корректно — сразу же его возвращаем,
                // тем самым завершая и метод, и его цикл while(true).
                return value;
            }
            // Если значение оказалось пустым — сообщаем об ошибке и НЕ выходим
            // из метода: цикл while(true) перейдёт на следующую итерацию
            // и снова покажет то же самое приглашение "prompt", давая
            // пользователю возможность ввести значение заново. Именно
            // благодаря этому циклу метод readRequiredString ГАРАНТИРОВАННО
            // возвращает непустую строку — вызывающему коду (например,
            // ExportMenuUI) не нужно САМОСТОЯТЕЛЬНО проверять результат
            // на пустоту после вызова этого метода, так как пустого
            // результата от него в принципе получить нельзя.
            System.out.println("Ошибка: значение не может быть пустым.");
        }
    }

    // Комментарий-описание метода.
    // Считывает целое число не меньше заданного минимума.

    // Используется, например, в AdminMenuUI.addService(...) для чтения
    // длительности услуги в минутах (с параметром min = 1).
    public static int readInt(Scanner scanner, String prompt, int min) {
        while (true) {
            System.out.print(prompt);
            // "try/catch (NumberFormatException)" — Integer.parseInt(...)
            // бросает именно это исключение, если переданная строка не
            // является корректной записью целого числа (например, пользователь
            // ввёл буквы, пустую строку или число с десятичной точкой) —
            // перехватываем это исключение здесь же, внутри цикла, вместо
            // того чтобы позволить ему "вылететь" наружу и прервать работу
            // всего приложения.
            try {
                // "scanner.nextLine().trim()" — как и выше, читаем всю строку
                // и убираем пробелы по краям перед попыткой разобрать её
                // как число (иначе, например, " 30" с пробелом впереди могло
                // бы не распознаться как корректное число, в зависимости
                // от реализации parseInt).
                int value = Integer.parseInt(scanner.nextLine().trim());
                // Проверяем, что введённое число не меньше допустимого
                // минимума (например, длительность услуги должна быть
                // хотя бы 1 минута — вызывающий код передаёт min = 1).
                if (value >= min) {
                    return value;
                }
                // Число распознано корректно, но не проходит по минимальному
                // значению — сообщаем об этом отдельным, более точным
                // сообщением (не "введите целое число", а именно "должно
                // быть не меньше X"), чтобы пользователь понимал КОНКРЕТНУЮ
                // причину ошибки.
                System.out.println("Ошибка: число должно быть не меньше " + min + ".");
            } catch (NumberFormatException e) {
                // Строка вообще не была похожа на целое число — печатаем
                // более общее сообщение об ошибке формата ввода.
                System.out.println("Ошибка: введите целое число.");
            }
            // В обоих случаях (число слишком маленькое ИЛИ строка не была
            // числом вообще) метод НЕ завершается через return, а переходит
            // на следующую итерацию цикла while(true), снова показывая
            // приглашение к вводу.
        }
    }

    // Комментарий-описание метода.
    // Считывает длинное целое число не меньше заданного значения.

    // Метод почти ДОСЛОВНО повторяет структуру readInt(...) выше — те же
    // шаги (печать приглашения, попытка разбора числа, проверка минимума,
    // обработка NumberFormatException), только работает с типом "long"
    // вместо "int" и вызывает Long.parseLong(...) вместо Integer.parseInt(...).
    // Такое дублирование логики между readInt и readLong — осознанный
    // компромисс: в Java нет прямого способа написать ОДИН обобщённый метод,
    // одинаково работающий и с примитивным int, и с примитивным long
    // (обобщения/generics в Java не поддерживают примитивные типы
    // напрямую, а использование обёрточных классов Integer/Long через
    // generics усложнило бы код сравнения "value >= min" из-за особенностей
    // сравнения обёрточных объектных типов). Метод readLong используется,
    // например, в AdminMenuUI.findById(...)/updateService(...)/deleteService(...)
    // для чтения ID услуги (с параметром min = 1, так как id не может быть
    // меньше 1).
    public static long readLong(Scanner scanner, String prompt, long min) {
        while (true) {
            System.out.print(prompt);
            try {
                long value = Long.parseLong(scanner.nextLine().trim());
                if (value >= min) {
                    return value;
                }
                System.out.println("Ошибка: число должно быть не меньше " + min + ".");
            } catch (NumberFormatException e) {
                System.out.println("Ошибка: введите целое число.");
            }
        }
    }

    // Комментарий-описание метода.
    // Считывает цену и корректно обрабатывает запятую в числе.

    // Используется, например, в AdminMenuUI.addService(...)/updateService(...)
    // и в AnalyticsMenuUI.cheaperThan(...) для чтения денежных сумм.
    public static BigDecimal readMoney(Scanner scanner, String prompt) {
        while (true) {
            System.out.print(prompt);
            try {
                // "scanner.nextLine().trim().replace(',', '.')" — сначала
                // читаем строку и убираем пробелы по краям, а затем ЗАМЕНЯЕМ
                // в ней ВСЕ символы запятой на точку. Это сделано специально
                // для удобства пользователя: в русскоязычной традиции
                // десятичные дроби принято записывать через запятую
                // (например, "2500,50"), тогда как конструктор BigDecimal
                // (как и большинство встроенных в Java средств разбора чисел)
                // понимает только точку как разделитель дробной части
                // (например, "2500.50"). Без этой замены ввод "2500,50"
                // вызвал бы NumberFormatException, хотя с точки зрения
                // пользователя это абсолютно корректная запись цены.
                BigDecimal value = new BigDecimal(scanner.nextLine().trim().replace(',', '.'));
                // "value.compareTo(BigDecimal.ZERO) >= 0" — для BigDecimal,
                // как объектного (а не примитивного) числового типа, нельзя
                // напрямую использовать операторы "<", ">", ">=" и т.п. —
                // вместо этого используется метод compareTo(...), который
                // возвращает отрицательное число, ноль или положительное
                // число в зависимости от того, МЕНЬШЕ, РАВНО или БОЛЬШЕ
                // сравниваемое значение относительно аргумента. Здесь
                // "результат >= 0" означает "value больше или равно нулю" —
                // то есть проверяем, что введённая цена НЕ отрицательная
                // (ноль разрешён — бесплатная услуга, по-видимому, допустима).
                if (value.compareTo(BigDecimal.ZERO) >= 0) {
                    return value;
                }
                System.out.println("Ошибка: цена не может быть отрицательной.");
            } catch (NumberFormatException e) {
                // Конструктор "new BigDecimal(String)" бросает
                // NumberFormatException, если переданная строка вообще
                // не является корректной записью числа (например, буквы,
                // пустая строка, несколько точек и т.п.) — перехватываем
                // это здесь же и просим ввести число заново, показывая
                // пользователю ПРИМЕР ожидаемого формата ("2500.00"),
                // чтобы было понятнее, что именно от него хотят.
                System.out.println("Ошибка: введите число, например 2500.00.");
            }
        }
    }

    // Комментарий-описание метода.
    // Считывает ответ типа да/нет.

    // Используется, например, в AdminMenuUI.deleteService(...) для запроса
    // подтверждения перед удалением услуги.
    public static boolean readYesNo(Scanner scanner, String prompt) {
        while (true) {
            // "prompt + " (д/н): "" — к переданному вопросу ("Удалить эту
            // услугу?") добавляется подсказка о допустимом формате ответа —
            // это удобнее, чем требовать от каждого вызывающего метода
            // самостоятельно прописывать "(д/н)" в тексте своего вопроса.
            System.out.print(prompt + " (д/н): ");
            // ".toLowerCase()" — приводим введённый ответ к нижнему регистру
            // ПЕРЕД сравнением, чтобы пользователь мог ответить как "Да",
            // так и "да", "ДА", "Y", "y" и т.д. — регистр введённых букв
            // не должен иметь значения для распознавания ответа.
            String value = scanner.nextLine().trim().toLowerCase();
            // Проверяем СРАЗУ НЕСКОЛЬКО вариантов, которые пользователь мог
            // ввести как "да": однобуквенный русский ("д"), полное русское
            // слово ("да"), однобуквенный латинский, характерный для
            // англоязычных программ ("y" — от "yes"), и полное английское
            // слово ("yes") — такая "всеядность" ввода снижает вероятность
            // того, что пользователь введёт вроде бы разумный ответ,
            // который программа не распознает.
            if (value.equals("д") || value.equals("да") || value.equals("y") || value.equals("yes")) {
                return true;
            }
            // Симметрично проверяем варианты ответа "нет" — тот же набор
            // из четырёх вариантов, что и для "да", только с отрицательным
            // смыслом.
            if (value.equals("н") || value.equals("нет") || value.equals("n") || value.equals("no")) {
                return false;
            }
            // Если введённый текст не совпал НИ С ОДНИМ из восьми
            // распознаваемых вариантов (ни "да", ни "нет" в каком-либо виде) —
            // сообщаем об ошибке и, как и во всех остальных методах этого
            // класса, НЕ выходим из цикла while(true), а снова показываем
            // тот же вопрос, пока не будет получен один из понятных
            // программе ответов.
            System.out.println("Ошибка: введите д/н.");
        }
    }
}