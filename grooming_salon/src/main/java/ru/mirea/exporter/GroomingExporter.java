// Пакет, к которому принадлежит класс. "exporter" — по смыслу сюда кладут код,
// отвечающий за выгрузку данных во внешние форматы (CSV, PDF и т.п.),
// в отличие от "analytics" (расчёты) или "model" (сами данные).
package ru.mirea.exporter;

// Импортируем GroomingService из другого пакета (ru.mirea.model) — без импорта
// компилятор не знал бы, что это за тип, так как класс объявлен не здесь.
import ru.mirea.model.GroomingService;

// IOException — checked-исключение (проверяемое компилятором), которое выбрасывают
// практически все операции ввода-вывода в Java (чтение/запись файлов, сети и т.д.),
// так как файловая система — вещь ненадёжная: файл может быть занят, диск может
// быть переполнен, прав может не хватать и т.п. Компилятор ЗАСТАВЛЯЕТ либо
// обработать это исключение через try-catch, либо объявить "throws IOException"
// у метода (как сделано ниже) и переложить обработку на вызывающий код.
import java.io.IOException;

// StandardCharsets — класс с готовыми константами кодировок текста (UTF-8, ASCII и т.д.).
// Нужен, чтобы явно указать, В КАКОЙ кодировке записывать текст в файл — если кодировку
// не указывать явно, Java возьмёт кодировку "по умолчанию" для операционной системы,
// а она может отличаться на разных компьютерах (например, Windows-1251 vs UTF-8),
// из-за чего кириллица в файле может превратиться в "кракозябры" на другой машине.
import java.nio.charset.StandardCharsets;

// Files — класс с готовыми статическими методами для работы с файлами:
// создание папок, чтение, запись и т.д. Часть современного API работы с файлами (NIO.2),
// пришедшего на замену старому java.io.File.
import java.nio.file.Files;

// Path — представляет путь к файлу или папке в файловой системе (например,
// "C:/reports/export.csv" или "/home/user/export.csv"). Пришёл на замену
// старому классу java.io.File и умеет работать одинаково на разных ОС.
import java.nio.file.Path;

// List — интерфейс списка; используется как тип параметра метода
// (принимаем список услуг, которые нужно выгрузить).
import java.util.List;

// "public" — класс должен быть виден и использоваться из других пакетов проекта
// (например, из сервисного слоя, который вызывает "выгрузи мне услуги в CSV").
// Если бы класс не был public, никакой код за пределами пакета ru.mirea.exporter
// не смог бы вызвать его метод exportToCsv.
//
// "final" — запрещает создавать наследников этого класса (никто не сможет написать
// "class MyExporter extends GroomingExporter"). Это осознанное архитектурное решение:
// класс представляет собой простой "набор статических утилитных функций" без
// какого-либо состояния (полей с данными) и без задумки на расширение поведения
// через наследование — поэтому "final" здесь служит документацией того,
// что класс не предназначен для наследования, и одновременно небольшой защитой
// от случайного/некорректного расширения такого класса.
public final class GroomingExporter {

    // Приватный (без модификаторов доступа снаружи) конструктор БЕЗ параметров и
    // БЕЗ
    // тела (пустые фигурные скобки). Смысл: запретить кому-либо создавать объект
    // класса через "new GroomingExporter()". Это стандартный приём для
    // классов-утилит
    // (у которых все методы статические, а самому классу не нужно хранить состояние
    // в виде полей объекта — у него просто нет причин существовать в виде
    // экземпляра).
    // Если бы конструктор не объявили явно, Java автоматически создала бы ПУБЛИЧНЫЙ
    // конструктор без параметров, и тогда любой код смог бы написать
    // "new GroomingExporter()", что не имело бы смысла и вводило бы в заблуждение.
    private GroomingExporter() {
    }

    // "public" — метод должен вызываться извне класса (сервисы, контроллеры и
    // т.д.).
    // "static" — метод вызывается через ИМЯ КЛАССА
    // (GroomingExporter.exportToCsv(...)),
    // а не через объект (new GroomingExporter().exportToCsv(...)), потому что у
    // класса
    // нет смысла создавать экземпляры (см. приватный конструктор выше) — вся логика
    // метода не зависит от состояния конкретного объекта.
    // "void" — метод ничего не возвращает: его цель — побочный эффект (записать
    // файл
    // на диск), а не вычислить и вернуть значение.
    // "throws IOException" — метод явно предупреждает вызывающий код: "внутри меня
    // происходит работа с файлами, и она может завершиться ошибкой ввода-вывода".
    // Так как IOException — checked-исключение, метод ОБЯЗАН либо поймать его сам
    // (try-catch), либо, как здесь, "передать ответственность" вызывающему коду
    // через throws — тогда уже ВЫЗЫВАЮЩИЙ метод должен будет либо обработать
    // IOException, либо тоже указать throws у себя.
    //
    // Параметры:
    // services — список услуг для выгрузки;
    // target — путь (Path) к файлу, в который нужно записать CSV.
    public static void exportToCsv(List<GroomingService> services, Path target) throws IOException {

        // Защита от null: если вызывающий код забыл передать список услуг,
        // лучше сразу упасть с понятной ошибкой "Список услуг не может быть null",
        // чем получить непонятный NullPointerException чуть ниже на строке "for (... :
        // services)".
        if (services == null) {
            // IllegalArgumentException — стандартное unchecked-исключение (не требует
            // объявления throws), которое принято бросать при некорректном аргументе
            // метода.
            throw new IllegalArgumentException("Список услуг не может быть null.");
        }

        // StringBuilder — класс для ЭФФЕКТИВНОГО построения строки по частям.
        // Обычная конкатенация строк через "+" в цикле (String csv = csv + "...")
        // на каждой итерации создаёт НОВЫЙ объект String в памяти (строки в Java
        // неизменяемы), что медленно при большом количестве повторений.
        // StringBuilder же хранит содержимое во ВНУТРЕННЕМ изменяемом массиве символов
        // и просто дописывает в него новые куски — это значительно быстрее для циклов.
        StringBuilder csv = new StringBuilder();

        // .append(...) — добавляет переданный текст в конец StringBuilder'а
        // и возвращает САМ StringBuilder, что позволяет "цеплять" вызовы через точку
        // подряд (см. цикл ниже) — этот приём называется fluent-интерфейс/цепочка
        // вызовов.
        // Здесь добавляем строку-заголовок CSV-файла — названия столбцов,
        // разделённые запятыми, и "\n" — символ переноса строки, чтобы следующая
        // добавленная строка данных начиналась с новой строки файла.
        csv.append("id,title,duration_minutes,price,description\n");

        // Обычный цикл "for-each" — проходим по каждому элементу списка services
        // по очереди, на каждой итерации "service" ссылается на текущую услугу.
        for (GroomingService service : services) {
            csv.append(service.id()) // Добавляем id услуги (число превращается в строку автоматически).
                    .append(',') // Добавляем запятую — разделитель CSV-столбцов.
                    .append(escape(service.title())) // Название — через escape(), см. метод ниже (защита от
                                                     // спецсимволов CSV).
                    .append(',')
                    .append(service.durationMinutes()) // Длительность в минутах (примитивное число).
                    .append(',')
                    .append(service.price()) // Цена (BigDecimal — при добавлении в StringBuilder
                                             // автоматически вызывается его toString()).
                    .append(',')
                    .append(escape(service.description())) // Описание — тоже через escape(), так как
                                                           // в описании чаще всего встречаются запятые/переносы строк.
                    .append('\n'); // Перенос строки — переходим к следующей услуге на новой строке файла.
        }

        // Перед записью файла убеждаемся, что папка, в которую мы пишем, существует.
        // target.getParent() — возвращает Path родительской папки файла (например,
        // для "reports/export.csv" вернёт "reports"). Если файл указан БЕЗ пути к папке
        // (просто "export.csv"), getParent() вернёт null — в этом случае мы используем
        // Path.of(".") — специальное обозначение "текущая рабочая директория".
        // Тернарный оператор "условие ? значение_если_true : значение_если_false"
        // компактно заменяет if/else в одно выражение.
        //
        // Files.createDirectories(...) создаёт всю цепочку недостающих папок
        // (аналог команды "mkdir -p" в консоли) — если папки уже существуют,
        // метод просто ничего не делает и не выбрасывает ошибку.
        Files.createDirectories(target.getParent() == null ? Path.of(".") : target.getParent());

        // Files.writeString(...) — записывает переданную строку в файл по указанному
        // пути.
        // csv.toString() — превращаем накопленный StringBuilder обратно в обычную
        // неизменяемую String (StringBuilder сам по себе не является строкой,
        // это отдельный служебный класс для построения строк).
        // StandardCharsets.UTF_8 — явно указываем кодировку записи, чтобы кириллица
        // (названия услуг на русском) сохранилась корректно на любой системе.
        // Если файл target уже существовал, writeString() по умолчанию ПОЛНОСТЬЮ
        // перезапишет его содержимое (создаёт заново или обрезает существующий).
        Files.writeString(target, csv.toString(), StandardCharsets.UTF_8);
    }

    // "private" — метод используется ТОЛЬКО внутри этого класса (в exportToCsv
    // выше)
    // и не предназначен для вызова снаружи — это внутренняя техническая деталь
    // реализации, а не часть публичного "контракта" класса.
    // "static" — как и весь класс, не привязан к конкретному объекту.
    // Метод решает конкретную задачу формата CSV: "экранирование" (escaping) —
    // безопасное оформление текста, который сам может содержать запятые, кавычки
    // или переносы строк, чтобы такой текст не сломал структуру CSV-файла
    // (иначе, например, запятая ВНУТРИ названия услуги была бы воспринята
    // при чтении файла как разделитель между столбцами).
    private static String escape(String value) {

        // Если значение поля не заполнено (null), в CSV записываем просто пустую
        // строку вместо текста "null" — иначе в файле появилось бы буквальное
        // слово "null" вместо пустой ячейки, что выглядело бы как ошибка данных.
        if (value == null) {
            return "";
        }

        // Правило формата CSV: если в тексте встречается двойная кавычка ("),
        // её нужно "удвоить" (заменить на две подряд идущие кавычки ""),
        // чтобы при последующем чтении файла парсер CSV не спутал эту кавычку
        // с кавычкой, ОБРАМЛЯЮЩЕЙ всё значение (см. ниже).
        // .replace("\"", "\"\"") — здесь "\"" это способ записать символ кавычки
        // внутри Java-строки (кавычка — специальный символ, начинающий/завершающий
        // строку, поэтому перед ней ставится обратный слеш "\" — это называется
        // экранирование СИМВОЛА в исходном коде Java, не путать с экранированием CSV
        // из названия метода — это разные вещи с похожим словом).
        String normalized = value.replace("\"", "\"\"");

        // Проверяем, есть ли в тексте ХОТЯ БЫ ОДИН из "опасных" для CSV символов:
        // "," — сам разделитель столбцов (текст с запятой без кавычек "разъехался" бы
        // на два столбца при чтении файла);
        // "\n" — перенос строки (Unix/Linux-стиль) — без кавычек текст "разорвал" бы
        // одну строку данных на две строки в файле;
        // "\r" — перенос строки (Windows-стиль, "возврат каретки"), встречается вместе
        // с "\n" или отдельно в файлах, созданных на Windows;
        // "\"" — сама кавычка (уже удвоенная строкой выше) — раз в тексте есть кавычки,
        // весь текст всё равно нужно обернуть в кавычки, чтобы читатель CSV понял,
        // где значение начинается и заканчивается.
        if (normalized.contains(",") || normalized.contains("\n") || normalized.contains("\r")
                || normalized.contains("\"")) {
            // Если найден хотя бы один из этих символов — оборачиваем ВЕСЬ текст
            // в двойные кавычки. '"' + normalized + '"' — конкатенация строки
            // с символами кавычек по краям. Это стандартное правило формата CSV:
            // значение в кавычках может содержать внутри себя запятые и переносы строк,
            // и парсер CSV не будет считать их разделителями, пока не встретит
            // ЗАКРЫВАЮЩУЮ кавычку.
            return '"' + normalized + '"';
        }

        // Если ни одного "опасного" символа не найдено — возвращаем текст как есть,
        // оборачивать в кавычки незачем (это сделало бы файл менее читаемым без
        // необходимости).
        return normalized;
    }
}