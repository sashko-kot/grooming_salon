// Пакет, к которому принадлежит этот тип. "model" — по смыслу сюда кладут классы,
// описывающие ДАННЫЕ предметной области (сущности), в отличие от "exporter"
// (выгрузка) или "analytics" (расчёты) — модель ничего не считает и никуда не
// экспортирует, она просто ХРАНИТ информацию об одном объекте реального мира.
package ru.mirea.model;

// Комментарий-описание типа: кратко объясняет, ЗАЧЕМ он нужен и что хранит.
// Модель записи на приём.
// Здесь хранится информация о клиенте, питомце и детали записи.

// "public" — тип должен быть виден и использоваться из ЛЮБОГО другого пакета
// проекта (сервисы, контроллеры, экспортёры и т.д. — всем им нужно работать
// с объектами Appointment), поэтому доступ открыт максимально широко.
//
// "record" (а не обычный "class") — ключевое слово Java (появилось в Java 16),
// специально созданное для описания ПРОСТЫХ НЕИЗМЕНЯЕМЫХ данных ("носителей данных",
// data carrier). Appointment — это именно такой случай: объект хранит набор полей
// одной записи на приём и не имеет собственного "поведения" (методов с бизнес-логикой) —
// он просто описывает, ЧТО ИЗ СЕБЯ представляет запись на приём.
//
// Если бы вместо record использовали обычный class, пришлось бы вручную писать:
//   1) приватные поля для каждого параметра (private final Long id; и т.д.);
//   2) конструктор, который принимает все параметры и присваивает их полям;
//   3) геттеры для каждого поля (getId(), getClientName() и т.д.);
//   4) метод equals() — чтобы можно было сравнивать два объекта "по значению"
//      (а не по тому, что это один и тот же объект в памяти);
//   5) метод hashCode() — согласованный с equals(), нужен, если объекты будут
//      использоваться, например, как ключи в HashMap или храниться в HashSet;
//   6) метод toString() — для удобного вывода объекта в консоль/логи в виде текста.
// Record генерирует ВСЁ ЭТО автоматически на основе списка компонентов в скобках,
// что резко сокращает количество кода для типов, которые нужны только для
// хранения данных — как раз случай Appointment.
//
// Важное следствие использования record: ВСЕ поля становятся неизменяемыми
// (final) автоматически. Это значит, что после создания объекта Appointment
// НЕЛЬЗЯ поменять, например, его статус — можно только СОЗДАТЬ НОВЫЙ объект
// Appointment с другим значением status (см. пример использования в самом низу).
// Такая неизменяемость — намеренное архитектурное решение: она делает объекты
// record потокобезопасными "из коробки" (несколько потоков могут одновременно
// читать один и тот же объект без риска гонок данных) и защищает от случайного
// изменения записи "где-то в середине" кода без создания нового объекта.
public record Appointment(

        // Список в скобках после имени record называется "компонентами записи"
        // (record components). Каждый компонент — это одновременно:
        // а) поле класса (приватное, неизменяемое — final);
        // б) параметр автоматически сгенерированного конструктора;
        // в) публичный метод-геттер с ТЕМ ЖЕ именем, что и компонент
        // (то есть для поля "id" геттер называется не getId(), а просто id() —
        // это отличается от классического стиля JavaBeans, принятого для обычных
        // классов, и является особенностью именно record).

        // "Long" (с большой буквы, объектный тип-обёртка), а НЕ примитивный "long" —
        // выбран специально, чтобы это поле МОГЛО хранить значение null.
        // У примитивного "long" нет "пустого" состояния — он всегда содержит
        // какое-то число (по умолчанию 0), и 0 нельзя однозначно отличить
        // от "идентификатор ещё не присвоен". Объектный Long же может быть null,
        // что удобно, например, для НОВОЙ записи, которая ещё не сохранена
        // в базу данных и которой сервер ещё не выдал настоящий id
        // (в таком случае поле id будет null до момента сохранения).
        Long id,

        // "String" — обычная строка. Здесь хранится имя клиента ЦЕЛИКОМ одной строкой
        // (без разделения на отдельные поля "имя" и "фамилия") — выбор простоты модели:
        // для записи на приём, судя по всему, не требуется отдельно оперировать
        // именем и фамилией клиента, достаточно единого текстового представления.
        String clientName,

        // Кличка питомца, которого записывают на услугу. Тоже простая строка —
        // модели не нужно хранить отдельный объект "Питомец" со своей историей,
        // породой и т.д., для записи на приём достаточно просто знать кличку.
        String petName,

        // Идентификатор услуги (например, "стрижка", "мытьё"), на которую записан
        // клиент. Тип "Long" (а не сам объект услуги GroomingService целиком) —
        // распространённый приём: вместо хранения ПОЛНОЙ вложенной сущности внутри
        // Appointment хранится только её ИДЕНТИФИКАТОР (внешний ключ), а сама услуга
        // при необходимости подгружается отдельно (например, через репозиторий/DAO
        // по этому id). Это уменьшает связанность между моделями и избегает
        // дублирования
        // (и устаревания) данных об услуге внутри каждой записи на приём.
        Long serviceId,

        // Уникальный код бронирования — по всей видимости, короткий буквенно-числовой
        // код, который выдаётся клиенту (например, на почту или в приложение),
        // чтобы клиент мог сослаться на свою запись, не называя её числовой id
        // (id обычно считается внутренним техническим полем базы данных,
        // а bookingCode — это "человекочитаемый" публичный идентификатор для клиента).
        String bookingCode,

        // Текущий статус записи в виде строки (например, "NEW", "CONFIRMED",
        // "CANCELLED", "COMPLETED" — конкретные значения не видны из этого файла,
        // так как тип поля — обычная String, а не перечисление).
        //
        // Важное архитектурное замечание: использование String вместо перечисления
        // (enum) для статуса — рабочий, но не самый строгий вариант. При таком подходе
        // компилятор НЕ проверяет, что в поле status попадёт одно из "разрешённых"
        // значений — теоретически туда можно записать любую произвольную строку,
        // включая опечатку вроде "CONFRIMED". Если бы вместо String использовали
        // enum (например, "enum AppointmentStatus { NEW, CONFIRMED, CANCELLED,
        // COMPLETED }"),
        // компилятор сам не позволил бы присвоить полю недопустимое значение,
        // и переключение по статусу (switch) можно было бы сделать исчерпывающим
        // и проверяемым компилятором. Использование String здесь может быть
        // осознанным упрощением (например, если статусы приходят "как есть"
        // из внешней системы или из базы данных в виде текста).
        String status) {

    // Тело record пустое — фигурные скобки есть, но внутри ничего не добавлено.
    // Это означает, что автор НЕ стал:
    // - добавлять свою явную реализацию конструктора (например, для проверки
    // аргументов на null или на пустую строку — такой конструктор называется
    // "компактным каноническим конструктором" и мог бы выглядеть так:
    // public Appointment {
    // if (clientName == null || clientName.isBlank()) {
    // throw new IllegalArgumentException("Имя клиента обязательно");
    // }
    // }
    // но в текущем виде record такой проверки нет — Appointment можно создать
    // даже с пустыми/некорректными строками, и это не вызовет ошибку);
    // - добавлять дополнительные вспомогательные методы (например, метод
    // "boolean isCancelled() { return "CANCELLED".equals(status); }" —
    // record, в отличие от "чистых" структур данных в других языках,
    // МОЖЕТ содержать собственные методы, если это нужно, — здесь автор
    // решил обойтись без них и оставить модель максимально простой).
}

