// // принимающий все компоненты в том порядке, в котором они объявлены в
// скобках.
// Appointment appointment = new Appointment(
// 1L, "Иванов Иван", "Барсик", 5L, "BR-2026-001", "NEW");
//
// // Чтение полей — через автоматически сгенерированные геттеры-методы,
// // названные ТОЧНО так же, как сами компоненты (без префикса "get").
// String client = appointment.clientName(); // "Иванов Иван"
// String status = appointment.status(); // "NEW"
//
// // Изменить status у СУЩЕСТВУЮЩЕГО объекта нельзя (все поля record
// неизменяемы) —
// // чтобы "обновить" запись, нужно создать НОВЫЙ объект Appointment с нужным
// // значением status, скопировав остальные поля из старого объекта:
// Appointment confirmed = new Appointment(
// appointment.id(), appointment.clientName(), appointment.petName(),
// appointment.serviceId(), appointment.bookingCode(), "CONFIRMED");