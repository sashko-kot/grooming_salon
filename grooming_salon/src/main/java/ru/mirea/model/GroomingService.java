// Пакет "model" — сюда помещают типы, описывающие ДАННЫЕ предметной области
// (сущности), а не логику расчётов (analytics) или выгрузки (exporter).
package ru.mirea.model;

// Обратите внимание: здесь НЕТ отдельной строки "import java.math.BigDecimal;"
// в начале файла — вместо этого ниже используется ПОЛНОЕ ("квалифицированное")
// имя класса "java.math.BigDecimal" прямо в месте объявления поля price.
// Это два РАВНОЗНАЧНЫХ способа сослаться на класс из другого пакета:
//   1) написать "import java.math.BigDecimal;" один раз вверху файла,
//      а дальше по всему файлу использовать короткое имя "BigDecimal";
//   2) не писать import вообще, а каждый раз, когда нужен этот класс,
//      писать его ПОЛНОЕ имя с пакетом — "java.math.BigDecimal".
// Оба варианта компилируются одинаково и не влияют на работу программы —
// это чисто вопрос стиля кода. Второй способ (без import) иногда используют,
// когда класс нужен всего один раз в файле и не хочется "захламлять"
// список импортов ради одного использования, либо когда в файле уже есть
// import другого класса с ТАКИМ ЖЕ коротким именем (например, если бы уже
// был импортирован какой-то другой "BigDecimal" из другого пакета —
// тогда пришлось бы либо использовать полное имя, либо императивно выбрать,
// какой из двух одноимённых классов импортировать).

// Комментарий-описание типа.
// Модель услуги салона.
// В этом объекте хранится название, длительность, цена и описание услуги.

// "public" — тип используется из других пакетов (analytics считает цены,
// exporter выгружает в CSV, значит обоим нужен доступ к GroomingService
// снаружи пакета ru.mirea.model), поэтому доступ открыт максимально широко.
//
// "record" (а не обычный "class") — используется, потому что GroomingService,
// как и Appointment из соседнего файла модели, представляет собой ПРОСТОЙ
// неизменяемый набор данных об одном объекте предметной области (услуге),
// а не объект с собственным сложным поведением. Record автоматически
// генерирует за нас:
//   - конструктор, принимающий все 5 полей в объявленном порядке;
//   - геттеры-методы с именами КАК У ПОЛЕЙ (id(), title(), durationMinutes(),
//     price(), description()) — без привычного префикса "get", это и есть
//     стиль record, отличающийся от классического стиля JavaBeans
//     (getId(), getTitle() и т.д.), принятого для обычных классов;
//   - equals() и hashCode() — сравнение двух GroomingService происходит
//     ПО ЗНАЧЕНИЮ всех полей, а не по ссылке (два объекта с одинаковыми
//     id/title/duration/price/description будут считаться равными);
//   - toString() — готовое текстовое представление вида
//     "GroomingService[id=1, title=Стрижка, durationMinutes=45, price=1500, description=...]"
//     для удобной печати в консоль или логи без ручного написания форматирования.
//
// Как и у Appointment, использование record означает, что ВСЕ поля объекта
// становятся неизменяемыми (final) — после создания объекта GroomingService
// нельзя, например, поменять его цену: если цену нужно обновить, придётся
// создать НОВЫЙ объект GroomingService с уже другим значением price,
// скопировав остальные поля из старого объекта (пример — в самом низу файла).
// Именно это свойство активно используется в классе GroomingAnalytics
// (см. соседний файл): методы там не изменяют переданные услуги "на месте",
// а лишь читают их данные (s.price(), s.durationMinutes() и т.д.) и строят
// на основе них новые списки/расчёты — что как раз характерно для работы
// с неизменяемыми record.
public record GroomingService(

        // Идентификатор услуги. Тип "Long" (объектная обёртка), а НЕ примитивный
        // "long" — по той же причине, что и в Appointment: объектный Long может
        // быть null, что удобно для представления "ещё не сохранённой в базу"
        // услуги, у которой настоящий id появится только после сохранения
        // (например, если id генерируется автоматически самой базой данных
        // при вставке строки — до этого момента в коде id попросту неизвестен).
        Long id,

        // Название услуги (например, "Стрижка", "Мытьё с сушкой"). Обычная
        // строка — простое текстовое поле без дополнительных ограничений
        // на уровне типа (проверка на пустоту/null, если она где-то нужна,
        // должна выполняться отдельно, снаружи этого record — само определение
        // record такую проверку не делает, тело record ниже пустое).
        String title,

        // Длительность услуги в минутах. Здесь используется примитивный тип
        // "int" (а не объектный "Integer"), в отличие от id (Long). Это осознанная
        // разница: длительность услуги — величина, которая ВСЕГДА должна быть
        // указана и не имеет смысла как "неизвестное" значение (услуга без
        // длительности физически не существует), поэтому null для неё не нужен,
        // и можно использовать более лёгкий и быстрый примитивный тип int
        // (не требует создания объекта-обёртки в памяти, как это было бы с Integer).
        // Именно поэтому в GroomingAnalytics метод getLongestService использует
        // Comparator.comparingInt(...) (а не обычный comparing) — специальную
        // версию для сравнения по примитивному int-полю без лишней "упаковки".
        int durationMinutes,

        // Цена услуги. Использован класс java.math.BigDecimal — специальный тип
        // Java для ТОЧНЫХ вычислений с деньгами и дробными числами, где важна
        // абсолютная точность (в отличие от double/float, которые могут давать
        // крошечные ошибки округления из-за внутреннего двоичного представления
        // дробных чисел — на деньгах такие ошибки недопустимы, даже мелкие
        // расхождения в копейках критичны для финансовых расчётов).
        // Имя класса написано ПОЛНОСТЬЮ (java.math.BigDecimal) прямо здесь,
        // а не через отдельный import — см. пояснение в самом начале файла.
        java.math.BigDecimal price,

        // Развёрнутое текстовое описание услуги — например, что конкретно
        // входит в услугу, какие материалы используются и т.д. Как и title,
        // это обычная строка без встроенных ограничений на уровне типа.
        String description) {

    // Тело record пустое — дополнительных проверок (например, что durationMinutes
    // должен быть положительным числом, а price не может быть отрицательным)
    // здесь НЕ добавлено. При желании такие проверки можно было бы вставить сюда
    // через компактный канонический конструктор, например:
    // public GroomingService {
    // if (durationMinutes <= 0) {
    // throw new IllegalArgumentException("Длительность должна быть положительной");
    // }
    // if (price != null && price.signum() < 0) {
    // throw new IllegalArgumentException("Цена не может быть отрицательной");
    // }
    // }
    // Но в текущем виде GroomingService доверяет вызывающему коду и не проверяет
    // корректность переданных значений самостоятельно.
}

